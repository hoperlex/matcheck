/**
 * Тесты на пересчёт цены к виду «с налогом».
 *
 * Числа взяты с боевых документов, а не выдуманы: главный смысл функции в том,
 * чтобы на экране сходилась арифметика строки, и проверять это надо на тех же
 * значениях, что видит менеджер.
 */
import { describe, it, expect } from 'vitest';
import { priceWithVat, priceWithoutVat } from './priceWithVat';

describe('priceWithVat — цена за единицу с налогом', () => {
  it('считает по ставке строки: боевой УПД № 203368', () => {
    // Вода питьевая: 15 шт по 240 ₽ (графа 4), стоимость с налогом 4 392 ₽.
    // Ровно тот документ, с которого началась задача: на экране 15 × 240 не
    // сходилось с показанной суммой.
    const withVat = priceWithVat('240', '22', '4392.00', '792.00');
    expect(withVat).toBe('292.8');
    // И теперь сходится: 15 × 292,80 = 4 392.
    expect(15 * Number(withVat)).toBeCloseTo(4392, 2);
  });

  it('держит четыре знака — столько хранит колонка price', () => {
    // До копеек округлять нельзя: карточка правится, и пара пересчётов
    // молча портила бы цену. Два знака показывает уже formatMoneyRu.
    expect(priceWithVat('908.20', '22', null, null)).toBe('1108.004');
    expect(priceWithVat('335.08', '22', null, null)).toBe('408.7976');
  });

  it('цена с четырьмя знаками переживает пару пересчётов', () => {
    // Боевая цена из базы: 11 позиций за месяц имеют больше двух знаков.
    // При округлении до копеек 66,294 возвращалось как 66,3 — тихая порча.
    const gross = priceWithVat('66.294', '22', null, null);
    expect(priceWithoutVat(Number(gross), '22', null, null)).toBe('66.294');
  });

  it('не верит абсурдной ставке из битого разбора', () => {
    // В графе 7 после плохого распознавания оказывается что угодно.
    // «2200 %» превратили бы 240 ₽ в 5 520 ₽ — правдоподобно и неверно.
    expect(priceWithVat('240', '2200', null, null)).toBe('240');
    expect(priceWithVat('240', '-5', null, null)).toBe('240');
    // На шапку при этом не переходим: она про весь документ, а не про строку.
    expect(priceWithVat('240', '2200', '4392.00', '792.00')).toBe('240');
  });

  it('нулевая ставка строки важнее ставки документа', () => {
    // Строка «Без НДС» внутри документа с налогом — законный случай.
    expect(priceWithVat('240', '0', '4392.00', '792.00')).toBe('240');
  });

  it('берёт ставку из шапки, когда в строке её нет', () => {
    // 179 позиций за месяц приходят без построчной ставки. Формула шапки —
    // та же, что в боевой валидации: vatSum / (totalSum − vatSum) × 100.
    // 4392 − 792 = 3600; 792 / 3600 = 22 %.
    expect(priceWithVat('240', null, '4392.00', '792.00')).toBe('292.8');
  });

  it('ставка строки важнее шапки', () => {
    // У документа может быть смесь ставок; построчная точнее агрегата.
    expect(priceWithVat('100', '10', '4392.00', '792.00')).toBe('110');
  });

  it('возвращает цену как есть, когда налога нет вовсе', () => {
    // 172 позиции за месяц — из документов без НДС. Там цена с налогом равна
    // цене, и это не повод ничего помечать.
    expect(priceWithVat('240', null, '3600.00', '0')).toBe('240');
    expect(priceWithVat('240', '0', null, null)).toBe('240');
    expect(priceWithVat('240', null, null, null)).toBe('240');
  });

  it('не выдумывает ставку из бессмысленной шапки', () => {
    // Налог больше суммы — документ разобран неверно. Показать исходную цену
    // честнее, чем посчитать по абсурдной ставке.
    expect(priceWithVat('240', null, '100', '500')).toBe('240');
    expect(priceWithVat('240', null, '100', '100')).toBe('240');
  });

  it('пустая цена остаётся пустой', () => {
    // В колонке будет прочерк, как и сейчас: цены нет в бумаге.
    expect(priceWithVat(null, '22', '4392', '792')).toBeNull();
    expect(priceWithVat('', '22', '4392', '792')).toBeNull();
    expect(priceWithVat('не число', '22', null, null)).toBeNull();
  });
});

describe('priceWithoutVat — обратный пересчёт при ручном вводе', () => {
  it('возвращает цену бланка из введённой с налогом', () => {
    expect(priceWithoutVat(292.8, '22', null, null)).toBe('240');
  });

  it('пара пересчётов сходится на боевых значениях', () => {
    // Именно этим свойством держится безопасность редактирования: то, что
    // пользователь увидел и не тронул, должно вернуться тем же числом.
    for (const [price, rate] of [
      ['240', '22'],
      ['908.20', '22'],
      ['1224.59', '22'],
      ['8250', '20'],
      ['104098.36', '22'],
    ] as const) {
      const shown = priceWithVat(price, rate, null, null);
      expect(priceWithoutVat(Number(shown), rate, null, null)).toBe(String(Number(price)));
    }
  });

  it('без ставки отдаёт введённое как есть', () => {
    expect(priceWithoutVat(240, null, null, null)).toBe('240');
    expect(priceWithoutVat(240, '0', null, null)).toBe('240');
  });

  it('пустой ввод остаётся пустым', () => {
    expect(priceWithoutVat(null, '22', null, null)).toBeNull();
  });
});
