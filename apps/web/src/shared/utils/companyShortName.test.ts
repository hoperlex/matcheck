import { describe, it, expect } from 'vitest';
import { shortenCounterpartyName } from './companyShortName';

// Хелпер применяется в списке Документов ко всем трём сторонам сразу, поэтому
// у него две обязанности: сократить форму собственности и отдать «—» вместо
// пустоты (в колонках его результат используется напрямую, без `?? '—'`).
describe('shortenCounterpartyName', () => {
  it.each([
    ['Общество с ограниченной ответственностью «АЛЬЯНС»', 'ООО «АЛЬЯНС»'],
    ['ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ "СУ-10"', 'ООО "СУ-10"'],
    ['Акционерное общество «Мосинжпроект»', 'АО «Мосинжпроект»'],
    ['Публичное акционерное общество «Сбербанк»', 'ПАО «Сбербанк»'],
    ['Индивидуальный предприниматель Иванов И.И.', 'ИП Иванов И.И.'],
  ])('%s → %s', (input, expected) => {
    expect(shortenCounterpartyName(input)).toBe(expected);
  });

  it('уже сокращённое название не трогает', () => {
    expect(shortenCounterpartyName('ООО «СУ-10»')).toBe('ООО «СУ-10»');
  });

  it('название без формы собственности возвращает как есть', () => {
    expect(shortenCounterpartyName('Базальтовые Огнезащитные Системы')).toBe(
      'Базальтовые Огнезащитные Системы',
    );
  });

  it('пустое значение → прочерк', () => {
    expect(shortenCounterpartyName(null)).toBe('—');
    expect(shortenCounterpartyName(undefined)).toBe('—');
    expect(shortenCounterpartyName('   ')).toBe('—');
  });

  it('форма собственности сокращается только в начале строки', () => {
    // «Филиал общества с ограниченной ответственностью …» — не тот случай,
    // где можно резать: сокращение исказило бы смысл.
    expect(shortenCounterpartyName('Филиал общества с ограниченной ответственностью «Х»')).toBe(
      'Филиал общества с ограниченной ответственностью «Х»',
    );
  });
});
