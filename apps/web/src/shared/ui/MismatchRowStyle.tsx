/**
 * Подсветка строки, к которой сверка документа предъявила претензию.
 *
 * Одно правило на всё приложение: раньше оно жило внутри модалки документа, и
 * карточка операции завела бы вторую копию. Один и тот же смысл — «этой строке
 * не верь» — обязан выглядеть одинаково в обоих местах, иначе читается как два
 * разных сигнала.
 *
 * Два селектора, потому что строка рисуется двумя способами: `td` — десктопная
 * таблица, второй — карточный режим ResponsiveTable на узком экране, где строки
 * это List.Item, а не ячейки.
 */
export function MismatchRowStyle() {
  return (
    <style>{`
      .matcheck-row-mismatch td { background-color: #fff7e6 !important; }
      .ant-list-item.matcheck-row-mismatch { background-color: #fff7e6; }
    `}</style>
  );
}
