import { useAuthStore } from '../stores/auth';

/**
 * Пользуется ли текущий пользователь локальной базой (IndexedDB) для операций
 * и документов.
 *
 * Наблюдатель (observer) — нет. Он видит только свои объекты и ничего не
 * меняет, а локальная копия переживает потерю доступа: приёмку перенесли на
 * чужой объект, сервер отвечает 404, а форма подставила бы сохранённый снимок
 * (KppPage: «Offline или 404 — отдаём локальный snapshot»). Поэтому для него
 * снимки не пишутся и не читаются, а отказ сервера показывается как есть.
 * Запоздалый ответ, начатый до смены доступа, тоже ничего не запишет.
 *
 * Остальным ролям — как было: на планшете и в PWA локальная база держит работу
 * без сети.
 */
export function localCacheEnabled(): boolean {
  return useAuthStore.getState().user?.role !== 'observer';
}
