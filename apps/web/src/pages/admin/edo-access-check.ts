/**
 * Что показать по итогу «Проверить доступ».
 *
 * Правило вынесено из вёрстки, потому что это именно правило: три разные
 * неполадки лечатся тремя разными действиями, и путать их нельзя.
 *
 * Отдельно стоит случай «ящиков ноль». Проверка прав в нём даже не выполняется:
 * уровень доступа спрашивают у конкретного ящика, а его нет. Раньше экран в
 * этом случае писал «Прав недостаточно» — то есть отправлял администратора
 * настраивать права там, где надо добавить учётную запись в организацию.
 */
import type { EdoCheckResult } from '@matcheck/contracts';

export type AccessVerdict = {
  kind: 'ok' | 'blocked' | 'no_boxes' | 'limited_access';
  title: string;
  description: string;
};

export function describeAccessCheck(result: EdoCheckResult): AccessVerdict {
  if (result.employee.isBlocked) {
    return {
      kind: 'blocked',
      title: 'Учётная запись заблокирована',
      description:
        'В Диадоке эта учётная запись заблокирована — доступ к документам ей закрыт независимо от прав.',
    };
  }

  if (result.boxes.length === 0) {
    return {
      kind: 'no_boxes',
      title: 'Учётная запись не видит ни одного ящика',
      description:
        'Токен получен, но Диадок не вернул ни одной организации: учётная запись, под которой выпущен refresh-токен, не числится в них сотрудником. Добавьте её сотрудником нужной организации с доступом ко всем документам — интеграция никого не регистрирует сама, потому что только читает.',
    };
  }

  if (!result.employee.hasRequiredAccess) {
    return {
      kind: 'limited_access',
      title: 'Прав недостаточно',
      description:
        'Интеграции нужен доступ ко всем документам ящика (AllDocuments). При ограниченном доступе часть документов не удастся прочитать.',
    };
  }

  return {
    kind: 'ok',
    title: 'Доступ есть',
    description: 'Учётная запись видит ящик и имеет доступ ко всем его документам.',
  };
}
