/**
 * Можно ли править название позиции операции — и если нет, то почему.
 *
 * Правило одно на четыре места (таблица и карточный режим × приёмка и
 * отгрузка). Раньше оно было списано в каждом из них отдельно и разъехалось:
 * в таблице приёмки стояло `!!materialId || isContractor`, а в карточном
 * режиме — только `!!materialId`, то есть подрядчик на узком экране правил
 * названия, хотя роль read-only. У отгрузки замка по справочнику не было вовсе.
 *
 * Вход — ЭФФЕКТИВНОЕ право редактирования (`can('operations.*', 'edit')`), а не
 * роль: проверка по имени роли не покрывает ни `observer`, ни будущие
 * изменения матрицы прав, и каждая новая read-only роль тихо получала бы
 * доступ к правке текста.
 */
export type ItemNameLockInput = {
  /** Право менять операцию — из usePermissions, а не из имени роли. */
  canEdit: boolean;
  /** Позиция связана со справочником материалов. */
  materialId: string | null | undefined;
};

export function itemNameLock({ canEdit, materialId }: ItemNameLockInput): string | null {
  if (!canEdit) return 'Недостаточно прав для правки названия';
  if (materialId) {
    // Замок снимется вместе с пересопоставлением материала на сервере: пока
    // его нет, исправленное имя не дошло бы до журнала материалов и отчётов
    // (там берётся materials.name), и человек считал бы, что исправил.
    return 'Название берётся из справочника материалов';
  }
  return null;
}
