/**
 * Можно ли заменить позиции формы серверным снимком.
 *
 * Карточка операции поллит сервер раз в 5 секунд, и у приёмки в confirmed_mol
 * любой сдвиг серверного updatedAt перегидратирует список позиций с новыми
 * clientKey. Пока человек печатает название, это стирает набранное прямо
 * из-под рук — а правят названия как раз в закрытых приёмках, куда менеджер
 * возвращается после инспектора.
 *
 * Правило вынесено из компонента, чтобы его можно было проверить: сам KppPage
 * рендер-тестами не покрыт (2400 строк и полтора десятка запросов).
 */
export function shouldReplaceItems(args: {
  /** Открыли другую операцию — прежние правки к ней отношения не имеют. */
  isFirstHydration: boolean;
  /** Сервер прислал снимок новее того, которым форма гидратирована. */
  hasNewServerSnapshot: boolean;
  /** В форме есть правка позиций, которую сервер ещё не подтвердил. */
  hasUnsavedItemEdits: boolean;
}): boolean {
  if (args.isFirstHydration) return true;
  if (!args.hasNewServerSnapshot) return false;
  // Осознанный компромисс: пока правка не отправлена, строки, добавленные с
  // планшета, в форме не появятся. При деструктивном upsert (DELETE + INSERT)
  // сохранение из «замороженной» формы их всё равно снесло бы, и от этого
  // защищает проверка исхода мутации — конфликт версий возвращает 409.
  return !args.hasUnsavedItemEdits;
}
