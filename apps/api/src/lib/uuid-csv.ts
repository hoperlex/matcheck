/**
 * Разбор csv-списков идентификаторов из query-параметров (`?siteIds=a,b,c`).
 *
 * Единственное место, где живёт проверка формата, — раньше их было три с
 * разной строгостью: маршруты приёмок и отгрузок проверяли полный шаблон
 * UUID, список документов не проверял ничего (`?siteIds=abc` уходил в
 * `id IN ('abc')` и валил запрос ошибкой Postgres), а выгрузка Excel
 * проверяла лишь длину и набор символов — так что 36 дефисов проходили.
 *
 * Невалидные элементы отбрасываются молча: кривая ссылка не должна ронять
 * запрос, а «фильтр по несуществующему id» и «фильтра нет» здесь совпадают.
 *
 * В отчётах (reports.ts) результат подставляется в raw SQL, поэтому проверка
 * здесь — ещё и граница безопасности: наружу проходят только строки строгого
 * формата.
 */
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function isUuid(value: string): boolean {
  return UUID_RE.test(value);
}

export function parseUuidCsv(raw: string | undefined | null): string[] {
  if (!raw) return [];
  return raw
    .split(',')
    .map((v) => v.trim())
    .filter(isUuid);
}
