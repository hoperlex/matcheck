-- Гейт: промпт должен существовать ровно в одном экземпляре, быть активным и
-- содержать признаки, ради которых заводится. Без последней проверки любая
-- будущая правка текста могла бы незаметно превратить его в общий промпт
-- накладных, а тогда второй проход начал бы дублировать первый.
DO $$
DECLARE
  cnt int;
  active_cnt int;
  has_form int;
  has_empty_rule int;
BEGIN
  SELECT count(*) INTO cnt FROM prompts WHERE doc_kind = 'transport_waybill_1t';
  IF cnt <> 1 THEN
    RAISE EXCEPTION 'Ожидался ровно один промпт «transport_waybill_1t», найдено %.', cnt;
  END IF;

  SELECT count(*) INTO active_cnt
    FROM prompts WHERE doc_kind = 'transport_waybill_1t' AND is_active = true;
  IF active_cnt <> 1 THEN
    RAISE EXCEPTION 'Промпт «transport_waybill_1t» должен быть активным: resolvePrompt без активной записи бросает ошибку.';
  END IF;

  SELECT count(*) INTO has_form
    FROM prompts WHERE doc_kind = 'transport_waybill_1t' AND content LIKE '%"tn_1t"%';
  IF has_form <> 1 THEN
    RAISE EXCEPTION 'В промпте «transport_waybill_1t» нет требования возвращать form = tn_1t.';
  END IF;

  SELECT count(*) INTO has_empty_rule
    FROM prompts
   WHERE doc_kind = 'transport_waybill_1t'
     AND content LIKE '%{"documents": []}%';
  IF has_empty_rule <> 1 THEN
    RAISE EXCEPTION 'В промпте «transport_waybill_1t» нет правила возвращать пустой список для чужих форм.';
  END IF;
END $$;
