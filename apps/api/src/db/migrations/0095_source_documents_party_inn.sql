-- ИНН сторон документа: продавец (графа 2), покупатель (графа 6),
-- грузополучатель (графа 4) — как напечатано в самом документе.
--
-- Зачем. В списке Документов под названием стороны нужен её ИНН: одноимённых
-- юрлиц много, и по названию менеджер не отличит нужное. Показывать было
-- нечего — распознанный ИНН нигде не хранился. Все producers (воркер УПД,
-- воркер накладных, ручной XML, ЭДО-поллер, заявки из почты) использовали его
-- один раз, чтобы найти или создать запись в suppliers/counterparties, и
-- выбрасывали. Сырой ответ модели остаётся только в журнале llm_calls, который
-- виден админу и живёт отдельно от документа.
--
-- Почему не берём ИНН из справочника вместо новых колонок. Берём — но лишь как
-- запасной путь. У стороны может не быть FK: графу 4 печатают без ИНН, а
-- counterparties.inn объявлен NOT NULL, связать такую сторону не с чем (см.
-- 0083). Плюс справочная запись правится людьми, а *_inn_raw отвечает на другой
-- вопрос — что стояло в документе на момент распознавания. DTO собирает
-- COALESCE(raw, справочник), поэтому исторические документы показывают ИНН
-- сразу, без бэкфилла.
--
-- Тип text и никаких CHECK: в документах встречаются «грязные» ИНН — с
-- пробелами, 11 знаков, подписью «ИНН …». Ровно поэтому suppliers.inn тоже
-- text. Нормализацию делает код (normalizeInn), а не БД: упавшая на CHECK
-- запись означала бы потерянный документ.

ALTER TABLE "source_documents"
  ADD COLUMN IF NOT EXISTS "supplier_inn_raw" text,
  ADD COLUMN IF NOT EXISTS "buyer_inn_raw" text,
  ADD COLUMN IF NOT EXISTS "consignee_inn_raw" text;
