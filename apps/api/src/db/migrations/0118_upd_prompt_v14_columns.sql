DO $$
DECLARE
  v14_count int;
  v14_extends_v13 int;
  v14_has_rules int;
  v14_active int;
  active_cnt int;
  active_name text;
BEGIN
  SELECT count(*) INTO v14_count
    FROM prompts WHERE doc_kind = 'upd' AND name = 'default v14';
  IF v14_count <> 1 THEN
    RAISE EXCEPTION 'Ожидался ровно один промпт «upd / default v14», найдено %. Проверьте наличие default v13.', v14_count;
  END IF;

  SELECT count(*) INTO v14_extends_v13
    FROM prompts v14
    JOIN prompts v13 ON v13.doc_kind = 'upd' AND v13.name = 'default v13'
   WHERE v14.doc_kind = 'upd' AND v14.name = 'default v14'
     AND position(v13.content in v14.content) = 1
     AND v14.content <> v13.content;
  IF v14_extends_v13 <> 1 THEN
    RAISE EXCEPTION 'default v14 не является дословным расширением default v13.';
  END IF;

  -- Проверяем ровно те правила, ради которых версия и заводится. Без признака
  -- «qty совпало с кодом СВОЕЙ единицы» самопроверка вырождается в ещё один
  -- запрет, а запреты в v13 уже есть и не работают.
  SELECT count(*) INTO v14_has_rules
    FROM prompts
   WHERE doc_kind = 'upd' AND name = 'default v14'
     AND content LIKE '%кодом единицы ЭТОЙ ЖЕ строки%'
     AND content LIKE '%52,000 м²%'
     AND content LIKE '%Пустая графа остаётся пустой%'
     AND content LIKE '%consigneeRaw%'
     AND content LIKE '%Год не додумывай%';
  IF v14_has_rules <> 1 THEN
    RAISE EXCEPTION 'В default v14 отсутствуют правила самопроверки, даты или consigneeRaw.';
  END IF;

  SELECT count(*) INTO v14_active
    FROM prompts WHERE doc_kind = 'upd' AND name = 'default v14' AND is_active = true;
  IF v14_active <> 0 THEN
    RAISE EXCEPTION 'default v14 не должен активироваться миграцией.';
  END IF;

  SELECT count(*) INTO active_cnt
    FROM prompts WHERE doc_kind = 'upd' AND is_active = true;
  IF active_cnt <> 1 THEN
    RAISE EXCEPTION 'Ожидался ровно один активный промпт «upd», найдено %.', active_cnt;
  END IF;

  SELECT name INTO active_name
    FROM prompts WHERE doc_kind = 'upd' AND is_active = true;
  IF active_name = 'default v14' THEN
    RAISE EXCEPTION 'default v14 не должен становиться активным в миграции.';
  END IF;
END $$;
