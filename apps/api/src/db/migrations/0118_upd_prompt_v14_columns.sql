-- как цена 52000; УПД № 2508/01 с восемью строками, где сумма равна
-- количеству, и итогом, собранным из этих подложных сумм.
--
-- Почему не «усилить формулировки». v13 УЖЕ содержит и таблицу кодов ОКЕИ, и
-- «qty — это НЕ код ОКЕИ», и соотношение qty × price ≈ sum × 100 / (100 +
-- vatRate). Модель это игнорирует. Повторять запрет третий раз бессмысленно —
-- v14 добавляет не запреты, а ПРОВЕРКИ: конкретные условия, которые модель
-- может применить к собственному ответу до того, как его вернёт, и признак,
-- по которому видно, что колонки съехали (qty совпало с кодом СВОЕЙ единицы).
--
-- Что ещё входит:
--   * дата документа — из строки «Счёт-фактура № … от …», а не из договора.
--     На бою: у № 201/21125711-7 модель вернула 24.11.2025 вместо 23.08.2026,
--     из-за чего экземпляр не склеился с остальными (склейка требует
--     совпадения даты) и инспектор увидел один УПД дважды;
--   * consigneeRaw — сырой текст графы 4. Нужен, чтобы отличать законное «он
--     же» от молчаливого копирования покупателя (см. Э2в): поле `consignee`
--     приходит от той же модели и доказательством не является;
--   * itemsCount — только если «Всего наименований» напечатано. Раньше просить
--     его было опасно: контракт был строгим и мусор в поле ронял разбор
--     целиком. С bef5c9b поле мягкое — нечисло становится null.
--
-- Вся редакция v13 копируется дословно, добавляется только хвост. Промпт
-- заводится НЕАКТИВНЫМ: выкат ничего не меняет, включение — вручную в
-- Администрирование → Промпты и только после
--   scripts/upd-prompt-ab.ts --base "default v13" --new "default v14"
-- на корпусе с денежной разметкой (41 документ, 73 позиции).
--
