-- УПД-промпт v10: наименование грузополучателя без адреса.
--
-- Зачем. Промпт v10 (миграция 0101) запретил переносить ИНН и КПП из чужих
-- граф, но про адрес не говорил ничего — а модель возвращает графу 4 строкой
-- целиком: «ООО "СУ-10", 127018, Город Москва, вн.тер.г. муниципальный округ
-- Марьина роща, ул Полковая, Дом 3, Строение 5». В форме 1137 наименование и
-- адрес и правда напечатаны вместе, поэтому формально модель права — но в
-- колонке портала должна стоять организация, а не организация с адресом.
--
-- Отдельный неочевидный вред: адрес ломает сравнение сторон. Для гарда
-- consigneeOwnIdentity строки «ООО "СУ-10", 127018, …» и «ООО "СУ-10"» — разные
-- организации, и у законного случая «он же» он отбросил бы верные реквизиты.
-- В коде это закрыто (адрес отрезается общей nameBeforeAddress ПОСЛЕ проверки
-- реквизитов), здесь — просим модель не присылать адрес вовсе.
--
-- Почему правим сам v10, а не заводим v11. Промпт ни разу не использовался: в
-- llm_calls нет ни одной ссылки на его prompt_id. Плодить версию, которой никто
-- не разбирал документы, значит засорять список в админке — там и так
-- шестнадцать строк. Гейт ниже проверяет это условие сам и валит миграцию,
-- если промпт всё же успели применить: менять текст промпта, которым что-то
-- разобрано, нельзя — записи журнала перестанут соответствовать своему тексту.
--
-- Что меняется: РОВНО одна строка — та же, которую переписала 0101. Правило про
-- реквизиты сохраняется целиком, к нему дописывается требование про адрес;
-- гейт проверяет наличие ОБОИХ.
--
-- Промпт остаётся НЕАКТИВНЫМ. Активация — вручную после прогона
-- scripts/upd-prompt-ab.ts --base "default v9" --new "default v10".
--
-- Откат: 0102_down.sql (возвращает текст строки к редакции 0101).

UPDATE "prompts"
   SET "content" = replace(
         "content",
         'Единственное исключение — буквальное «он же» в графе 4: это означает «грузополучатель тот же, что покупатель», и тогда повтори recipient целиком, вместе с его inn и kpp.',
         'Единственное исключение — буквальное «он же» в графе 4: это означает «грузополучатель тот же, что покупатель», и тогда повтори recipient целиком, вместе с его inn и kpp. В name пиши ТОЛЬКО наименование организации, как в ЕГРЮЛ: адрес, индекс, город, улицу и дом НЕ включай, даже если в графе они напечатаны следом через запятую в той же строке.'
       ),
       "updated_at" = now()
 WHERE "doc_kind" = 'upd'
   AND "name" = 'default v10'
   AND "is_active" = false
   -- Промпт, которым что-то уже разобрано, задним числом не переписываем.
   AND NOT EXISTS (SELECT 1 FROM "llm_calls" lc WHERE lc."prompt_id" = "prompts"."id");
--> statement-breakpoint
DO $$
DECLARE
  v10_id uuid;
  v10_calls int;
  v10_active boolean;
  v10_content text;
BEGIN
  SELECT id, content, is_active INTO v10_id, v10_content, v10_active
    FROM prompts WHERE doc_kind = 'upd' AND name = 'default v10';
  IF v10_id IS NULL THEN
    RAISE EXCEPTION 'Промпт «upd / default v10» не найден — миграция 0101 не применена?';
  END IF;

  IF v10_active THEN
    RAISE EXCEPTION 'Промпт «default v10» активен: правка текста активного промпта запрещена, сначала переключитесь на другую версию.';
  END IF;

  SELECT count(*) INTO v10_calls FROM llm_calls WHERE prompt_id = v10_id;
  IF v10_calls <> 0 THEN
    RAISE EXCEPTION 'Промптом «default v10» уже разобрано % документов — менять его текст задним числом нельзя, заведите новую версию.', v10_calls;
  END IF;

  -- Обе части правила обязаны присутствовать: UPDATE выше переписывает ту же
  -- строку, что и 0101, и потерять запрет на перенос реквизитов легко.
  IF v10_content NOT LIKE '%ТОЛЬКО если они напечатаны в самой графе 4%' THEN
    RAISE EXCEPTION 'В промпте «default v10» пропало правило о реквизитах из миграции 0101.';
  END IF;
  IF v10_content NOT LIKE '%адрес, индекс, город, улицу и дом НЕ включай%' THEN
    RAISE EXCEPTION 'В промпт «default v10» не добавилось правило об адресе — якорная строка не совпала, replace ничего не заменил.';
  END IF;
END $$;
