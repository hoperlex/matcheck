-- Откат 0102: убираем из промпта «upd / default v10» правило об адресе.
--
-- Возвращает строку графы 4 к редакции миграции 0101 (правило о реквизитах
-- остаётся). Обратный replace, а не переписывание текста целиком: остальная
-- часть промпта копировалась из v9 бит-в-бит, и трогать её при откате незачем.
--
-- Условия те же, что у прямой миграции: промпт неактивен и им ничего не
-- разобрано. Если это не так — откат не сработает молча, и это правильно:
-- менять текст промпта, которым разобраны документы, нельзя.
--
-- В meta/_journal.json НЕ регистрируется. Применять вручную:
--   psql "$DATABASE_URL" -1 -f apps/api/src/db/migrations/0102_down.sql
--   DELETE FROM drizzle.__drizzle_migrations WHERE hash = '<sha256 файла 0102>';

UPDATE "prompts"
   SET "content" = replace(
         "content",
         ' В name пиши ТОЛЬКО наименование организации, как в ЕГРЮЛ: адрес, индекс, город, улицу и дом НЕ включай, даже если в графе они напечатаны следом через запятую в той же строке.',
         ''
       ),
       "updated_at" = now()
 WHERE "doc_kind" = 'upd'
   AND "name" = 'default v10'
   AND "is_active" = false
   AND NOT EXISTS (SELECT 1 FROM "llm_calls" lc WHERE lc."prompt_id" = "prompts"."id");
