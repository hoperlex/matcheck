-- Откат 0097: роль «Наблюдатель» (observer).
--
-- SQL-части у отката НЕТ. PostgreSQL не умеет удалять значение из enum штатно
-- (ни ALTER TYPE ... DROP VALUE, ни аналога), а пересоздание типа user_role
-- потребовало бы перезаписи колонки users.role с эксклюзивной блокировкой
-- таблицы — цена несопоставима с выгодой: лишнее значение enum, на которое не
-- ссылается ни одна строка, не занимает места и ни на что не влияет.
--
-- Поэтому откат — процедурный, и его шаги ОБЯЗАТЕЛЬНЫ ДО выката старого кода:
-- тот про значение 'observer' не знает, и пользователь с такой ролью уронит
-- разбор UserDto (zod-enum) на каждом его запросе.
--
--   1) деактивировать всех наблюдателей — рвёт доступ независимо от сессий:
--        UPDATE users SET is_active = false WHERE role = 'observer';
--   2) перевести их на другую роль через админку (PATCH /admin/users/:id —
--      переход из observer инвалидирует сессии, см. routes/admin/users.ts);
--   3) убрать выданные права:
--        DELETE FROM role_page_permissions WHERE role = 'observer';
--   4) убедиться, что не осталось никого:
--        SELECT count(*) FROM users WHERE role = 'observer';   -- ожидается 0
--   5) только после этого — revert кода и деплой.
--
