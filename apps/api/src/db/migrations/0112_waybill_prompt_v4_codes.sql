## Общие поля (есть у обеих форм)

- `form` — `"tn_2116"` или `"os2"`.
- `docNumber` — номер документа из шапки (например «СП00-006047», «Д0000002518»): значение графы «№», стоящей рядом с датой составления документа.
  НИКОГДА не бери номер из таблицы «Коды» в правом верхнем углу бланка: строки «Форма по ОКУД», «по ОКПО», «по ОКТМО», «по ОКЕИ» содержат коды формы и организаций (7–8 цифр подряд, например 0345009 или 51160834), а не номер документа.
  Если графа «№» пуста или нечитаема — верни `docNumber: null`. Догадываться по соседним кодам запрещено: пустой номер лучше чужого.
- `docDate` — дата документа в формате YYYY-MM-DD.
- `confidence` — число 0..1, оценка качества распознавания именно этого документа.

## Для ТН-2116 (form = "tn_2116")

- `shipper` — Грузоотправитель из раздела 1:
