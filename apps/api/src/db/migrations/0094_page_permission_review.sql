-- Пятое действие матрицы прав: «Проверять» (review) — отметка проверки
-- качества на Операциях.
--
-- Зачем отдельное действие. Одной ячейкой operations.*:edit помечены четыре
-- маршрута с РАЗНЫМИ allow-list: PATCH /:id/review открыт admin/manager/monitor,
-- а /:id/flags, /:id/supplier-from-directory, /:id/link-source, /:id/share-link —
-- только admin/manager. Пока отметка сидела внутри edit, право монитора было
-- базовым, то есть никогда не считалось расширением и не обходило authorize:
-- галочка «Редактировать» у него включена, означает одну лишь отметку, а выдать
-- настоящую правку невозможно — включать нечего. Разведя действия, мы вернули
-- edit прямой смысл (у монитора снят по умолчанию, выдаётся как обычное
-- расширение), а отметку сделали самостоятельной, снимаемой галочкой.
--
-- Что это меняет в поведении: НИЧЕГО в день выката. Применение матрицы
-- по-прежнему выключено флагом PERMISSIONS_ENFORCE, а дефолт нового действия
-- (DEFAULT_MATRIX в packages/contracts/src/permissions.ts) в точности повторяет
-- сегодняшний allow-list маршрута review: manager и monitor.
--
-- ПОЧЕМУ НЕ ГОЛЫЙ DEFAULT false. Строка в этой таблице — override ЦЕЛИКОМ, а не
-- по колонкам: резолвер, найдя строку, берёт из неё значение действия как есть
-- и к дефолту уже не обращается. Новая колонка со значением false во всех
-- существующих строках означала бы «отметка проверки запрещена» — то есть при
-- включении флага manager и monitor молча потеряли бы её на тех страницах, где
-- админ когда-либо правил хоть одну галочку. Поэтому backfill проставляет ровно
-- базовое значение роли: review есть у manager и monitor на обеих страницах
-- Операций, больше нигде.
--
-- НЕДЕСТРУКТИВНО: добавление колонки + UPDATE уже существующих строк.
-- Таблица маленькая (десятки строк), блокировка незаметна.

ALTER TABLE "role_page_permissions"
  ADD COLUMN IF NOT EXISTS "can_review" boolean NOT NULL DEFAULT false;

UPDATE "role_page_permissions"
   SET "can_review" = true
 WHERE "role" IN ('manager', 'monitor')
   AND "page_id" IN ('operations.deliveries', 'operations.shipments');
