-- «Обработано» требует номер документа, но больше не требует дату и сумму.
--
-- Прежнее условие (номер И дата И сумма) держало на портале документы, по
-- которым приёмку провести можно: список материалов распознан, номер есть, а
-- шапочная сумма не пропечаталась на фотографии. Инспектор такие документы не
-- видел вовсе — на планшет уезжает только `parsed`.
--
-- Что вместо этого стережёт качество (см. domain/edo/upd-outcome.ts):
--   * без позиций или без номера документ остаётся needs_resolution;
--   * НЕПОЛНЫЙ список позиций (12 наименований в шапке против 3 распознанных)
--     — тоже needs_resolution: такая поставка приехала бы инспектору как
--     полная, и недостача вскрылась бы уже на приёмке;
--   * отсутствующий итог синтезируется по строкам с учётом НДС, и если хоть
--     одна строка невычислима — остаётся пустым, а не частичным.
--
-- Дата остаётся необязательной сознательно: подставлять дату поставки вместо
-- напечатанной в документе нельзя — расхождение всплыло бы при сверке с
-- бухгалтерией. Пустое поле честнее выдуманного.
--
-- НЕДЕСТРУКТИВНО: ограничение только ослабляется, данные не меняются.

ALTER TABLE "source_documents" DROP CONSTRAINT IF EXISTS "source_upd_required";

ALTER TABLE "source_documents" ADD CONSTRAINT "source_upd_required" CHECK (
  ("kind" <> 'upd')
  OR ("status" <> 'parsed')
  OR ("doc_number" IS NOT NULL)
);
