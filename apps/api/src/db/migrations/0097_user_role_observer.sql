-- Роль «Наблюдатель» (observer): web-only, БЕЗ единого права по умолчанию.
--
-- Зачем: роли contractor/monitor задумывались под конкретный сценарий и несут
-- свой набор базовых прав. Наблюдателю набор не задаётся вовсе — администратор
-- расставляет доступ галочками в «Администрирование → Роли». В PAGE_CATALOG[].base
-- роль не упоминается нигде, поэтому buildDefaultMatrix разворачивает её во все
-- false, а сервер трактует маршрут вне матрицы как закрытый для неё
-- (MATRIX_ONLY_ROLES в plugins/permissions.ts).
--
-- Значение enum 'observer' в этой миграции НЕ используется в DDL (других
-- изменений схемы нет вовсе), поэтому ADD VALUE безопасен — ошибки 55P04
-- «unsafe use of new value of enum type» здесь не возникает. Пользователи роли
-- заводятся позже, отдельными транзакциями.
--
-- Влияние на существующие данные: нулевое. Ни одна строка не меняется, ни один
-- пользователь роль не получает автоматически — до явного назначения в админке
-- RBAC этой роли «спит».
--
-- Откат: удалить value из enum PostgreSQL штатно не умеет — при откате оставляем
-- неиспользуемое значение (см. 0069/0070). Перед откатом кода обязательно
-- убрать пользователей с этой ролью, иначе старый код не разберёт их DTO.

ALTER TYPE "user_role" ADD VALUE IF NOT EXISTS 'observer';
