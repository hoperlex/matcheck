-- Второй проход распознавания: состояние повтора через картинку.
--
-- Зачем. Текстовый разбор УПД иногда отдаёт слабый результат (нет позиций, нет
-- итога) или падает целиком — например, при обрыве JSON по лимиту токенов: два
-- документа на проде так и остались parse_failed, потому что vision-фоллбэк
-- ловит только «нет текстового слоя» и «мусорный текст». Теперь такой документ
-- получает второй проход отдельным заданием очереди, и здесь хранится его
-- состояние.
--
-- Почему отдельная колонка, а не parse_error_details. Те перезаписываются
-- целиком в конце каждого разбора и при успехе становятся NULL. Маркер «повтор
-- уже заказан» там не пережил бы собственный проход, и документ ставил бы себе
-- задания по кругу. Эта колонка пишется только логикой второго прохода.
--
-- Форма значения:
--   { "state": "queued" | "done",
--     "requestedAt": "2026-08-06T11:31:10.736Z",
--     "mode": "vision",
--     "outcome": "replaced" | "kept_baseline" | "vision_failed",
--     "error": "текст ошибки vision" }
--
-- Аддитивно и nullable: старый образ продолжает работать на новой схеме.

ALTER TABLE "source_documents" ADD COLUMN IF NOT EXISTS "second_pass" jsonb;
--> statement-breakpoint
-- Частичный индекс: recovery ищет документы с незавершённым вторым проходом,
-- и это единственный запрос по колонке. Полный индекс на 200+ строк с NULL
-- смысла не имеет.
CREATE INDEX IF NOT EXISTS "source_documents_second_pass_queued_idx"
  ON "source_documents" (("second_pass"->>'state'))
  WHERE "second_pass" IS NOT NULL;
