-- Промпт М-15 v2: грузополучатель.
--
-- Зачем. В таблице «Документы» колонка «Грузополучатель» пуста у ВСЕХ
-- накладных. Причина не в качестве распознавания: активный промпт
-- «m15 / default v1» этого поля не просит вовсе — в разделе «Заголовок
-- документа» перечислены только supplier и recipient. Модель добросовестно
-- возвращает то, о чём спросили.
--
-- Что меняется относительно v1: РОВНО одна добавленная строка в разделе
-- «Заголовок документа». Остальной текст копируется из v1 бит-в-бит — потому
-- и делается через replace() над содержимым из БД, а не ручным переписыванием
-- 148 строк: так исключены незаметные расхождения в пробелах и формулировках,
-- из-за которых поехало бы распознавание уже работающих полей (номер, дата,
-- позиции, суммы).
--
-- Про семантику. В форме М-15 покупателя нет вовсе: есть «Кому» — организация,
-- которой фактически отпускают материалы. Она уже извлекается в recipient,
-- поэтому грузополучатель у накладных штатно совпадёт с покупателем, и обе
-- колонки портала покажут одну организацию. Это осознанный выбор: вариант
-- «убрать „Кому“ из recipient и оставить только в consignee» менял бы уже
-- работающее поле, а именно этого требовалось избежать.
--
-- Отдельно запрещаем «Через кого»: там печатают водителя или экспедитора —
-- физлицо, которое в справочник контрагентов попадать не должно.
--
-- Промпт заводится НЕАКТИВНЫМ. Активация — вручную в Администрирование →
-- Промпты, и только после прогона scripts/upd-prompt-ab.ts --doc-kind m15 на
-- выгруженных боевых накладных (scripts/corpus-export.ts): он сверяет v1 и v2
-- и показывает, не изменились ли номера, даты, суммы, позиции и confidence.
-- До активации прод продолжает работать на v1.
--
-- Откат: 0098_down.sql (удаляет v2; активным он к тому моменту быть не должен).

INSERT INTO "prompts" ("doc_kind", "name", "content", "is_active")
SELECT
  'm15',
  'default v2',
  replace(
    "content",
    '- recipient:  { inn, kpp, name } — «Кому» / организация-получатель.',
    '- recipient:  { inn, kpp, name } — «Кому» / организация-получатель.' || chr(10) ||
    '- consignee:  { inn, kpp, name } — грузополучатель: организация, которой фактически отпущены материалы (графа «Кому»). Если «Кому» пусто — возьми «Получатель». НЕ бери «Через кого» (это водитель или представитель, физлицо) и НЕ бери «Затребовал»/«Разрешил». ИНН в М-15 обычно не печатают — тогда inn: null, а name заполни. Если это тот же получатель, что в recipient, — повтори recipient.'
  ),
  false
FROM "prompts"
WHERE "doc_kind" = 'm15' AND "name" = 'default v1';
