-- Гейт: миграция идёт одной транзакцией, поэтому непройденная проверка
-- откатывает и вставку. Ловим три случая: v1 не найден (тогда INSERT ничего
-- не вставил), якорная строка не совпала (тогда replace вернул текст без
-- consignee, и v2 был бы копией v1) и случайная активация v2.
DO $$
DECLARE
  v2_count int;
  v2_ok int;
  v2_active int;
BEGIN
  SELECT count(*) INTO v2_count FROM prompts WHERE doc_kind = 'm15' AND name = 'default v2';
  IF v2_count <> 1 THEN
    RAISE EXCEPTION 'Ожидался ровно один промпт «m15 / default v2», найдено %. Проверьте, что «default v1» есть в таблице prompts.', v2_count;
  END IF;

  SELECT count(*) INTO v2_ok
    FROM prompts
   WHERE doc_kind = 'm15' AND name = 'default v2' AND content LIKE '%consignee%';
  IF v2_ok <> 1 THEN
    RAISE EXCEPTION 'В промпте «m15 / default v2» нет строки про consignee — якорная строка v1 не совпала, replace ничего не заменил.';
  END IF;

  SELECT count(*) INTO v2_active
    FROM prompts
   WHERE doc_kind = 'm15' AND name = 'default v2' AND is_active = true;
  IF v2_active <> 0 THEN
    RAISE EXCEPTION 'Промпт «m15 / default v2» не должен быть активным сразу после миграции.';
  END IF;
END $$;
