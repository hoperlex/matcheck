-- SHA-256 каждого принятого файла в реестре загрузки.
--
-- Зачем колонка, если хеш пачки уже есть. `source_bundles.content_hash` —
-- хеш КОМПЛЕКТА целиком, он отвечает на вопрос «эту пачку уже присылали». На
-- вопрос «какой из присланных сейчас файлов соответствует вон той строке
-- реестра» он не отвечает вовсе.
--
-- А вопрос этот появляется ровно в одном месте: часть файлов не залилась в S3,
-- поставщик жмёт «отправить ещё раз», и дозагрузить надо ТОЛЬКО пропавшие. По
-- имени сопоставлять нельзя — поставщики шлют IMG_0431.jpg пачками, имена
-- повторяются между отправками и внутри одной. По порядку в пачке — тоже:
-- человек мог переложить файлы местами. Хеш содержимого различает их
-- однозначно.
--
-- Хеш считается при приёме и сегодня (mergeSameFileAcrossZones в
-- ingest-bundle.ts), но никуда не сохраняется.
--
-- Второе применение — аудит: сверить, что в хранилище лежит именно то, что
-- прислали. Для этого тот же хеш пишется в метаданные S3-объекта
-- (x-amz-meta-sha256), и колонка становится опорой сверки.
--
-- NULL допустим: у строк, созданных до этой миграции, хеша нет и восстановить
-- его неоткуда — файл в S3 уже лежит, но пересчитывать хеш всего реестра
-- миграцией мы не будем.
--
-- НЕДЕСТРУКТИВНО: только новая nullable-колонка.

ALTER TABLE "bundle_import_items"
  ADD COLUMN IF NOT EXISTS "content_sha256" text;

COMMENT ON COLUMN "bundle_import_items"."content_sha256" IS
  'SHA-256 содержимого принятого файла (hex). NULL у строк до миграции 0106.';
