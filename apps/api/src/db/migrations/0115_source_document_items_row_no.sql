-- Напечатанный номер позиции из бланка документа.
--
-- Зачем колонка, если номер уже распознаётся. Промпт `upd` v13 просит модель
-- вернуть `rowNo` — номер из графы 1 бланка, — и валидатор по нему проверяет,
-- что строки идут подряд (items_sequence в upd-validation.ts). Но дальше номер
-- никуда не сохраняется: в source_document_items его нет, и после разбора он
-- существует только внутри одного вызова.
--
-- Из-за этого слепнут две вещи.
--
-- 1. Склейка экземпляров одной УПД. Поставщик сканирует оба экземпляра
--    (продавца и покупателя), сегментация делает из них два документа с
--    одинаковым номером, и склейка обязана понять: это КОПИИ (строки те же) или
--    ЧАСТИ одного документа (строки продолжаются). Напечатанные номера отвечают
--    на это прямо: у копий 1,2 и 1,2, у частей — 1,2 и 3,4. Без них приходится
--    гадать по совпадению количеств и сумм.
-- 2. Проверка целостности после склейки. validateUpdTotals поднимает строки из
--    БД, где rowNo нет, поэтому items_sequence уходит в skip — ровно там, где
--    задвоение строк и надо было бы поймать.
--
-- NULL допустим и останется у всех строк, разобранных до этой миграции:
-- восстановить номер задним числом неоткуда, документ придётся перераспознать.
--
-- НЕДЕСТРУКТИВНО: только новая nullable-колонка.

ALTER TABLE "source_document_items"
  ADD COLUMN IF NOT EXISTS "row_no" integer;

COMMENT ON COLUMN "source_document_items"."row_no" IS
  'Номер позиции, НАПЕЧАТАННЫЙ в бланке (графа 1). NULL у строк до миграции 0115 и у подпозиций вида «1а», которые числом не выражаются.';
