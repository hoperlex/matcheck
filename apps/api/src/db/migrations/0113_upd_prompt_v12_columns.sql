-- Гейт: v12 должен существовать ровно в одном экземпляре, быть дословным
-- расширением v11, нести все три правила и не менять того, чем документы
-- разбираются сегодня.
DO $$
DECLARE
  v12_count int;
  v12_extends_v11 int;
  v12_has_rules int;
  v12_active int;
  active_cnt int;
  active_name text;
BEGIN
  SELECT count(*) INTO v12_count
    FROM prompts WHERE doc_kind = 'upd' AND name = 'default v12';
  IF v12_count <> 1 THEN
    RAISE EXCEPTION 'Ожидался ровно один промпт «upd / default v12», найдено %. Проверьте наличие default v11.', v12_count;
  END IF;

  SELECT count(*) INTO v12_extends_v11
    FROM prompts v12
    JOIN prompts v11 ON v11.doc_kind = 'upd' AND v11.name = 'default v11'
   WHERE v12.doc_kind = 'upd' AND v12.name = 'default v12'
     AND position(v11.content in v12.content) = 1
     AND v12.content <> v11.content;
  IF v12_extends_v11 <> 1 THEN
    RAISE EXCEPTION 'default v12 не является дословным расширением default v11.';
  END IF;

  SELECT count(*) INTO v12_has_rules
    FROM prompts
   WHERE doc_kind = 'upd' AND name = 'default v12'
     AND content LIKE '%является разметкой заголовка%'
     AND content LIKE '%пока в графе 1 не появился новый номер%'
     AND content LIKE '%qty читается из графы 3, price — из графы 4%'
     AND content LIKE '%цена может иметь более двух знаков%';
  IF v12_has_rules <> 1 THEN
    RAISE EXCEPTION 'В default v12 отсутствует одно из трёх правил чтения таблицы.';
  END IF;

  SELECT count(*) INTO v12_active
    FROM prompts WHERE doc_kind = 'upd' AND name = 'default v12' AND is_active = true;
  IF v12_active <> 0 THEN
    RAISE EXCEPTION 'default v12 не должен активироваться миграцией.';
  END IF;

  -- Инвариант — «миграция не меняет то, чем документы разбираются сегодня»:
  -- активный остаётся ровно один и это не v12. Конкретное имя не проверяем:
  -- версию активируют вручную, и на разных стендах она разная (на бою v9, на
  -- локальном тестовом контейнере v8).
  SELECT count(*) INTO active_cnt
    FROM prompts WHERE doc_kind = 'upd' AND is_active = true;
  IF active_cnt <> 1 THEN
    RAISE EXCEPTION 'Ожидался ровно один активный промпт «upd», найдено %.', active_cnt;
  END IF;

  SELECT name INTO active_name
    FROM prompts WHERE doc_kind = 'upd' AND is_active = true;
  IF active_name = 'default v12' THEN
    RAISE EXCEPTION 'default v12 не должен становиться активным в миграции.';
  END IF;
END $$;
