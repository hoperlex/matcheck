-- УПД-промпт v12: числа привязываются к своей строке и своей графе.
--
-- Зачем. 19.08 приёмщики прислали три документа с неверной расшифровкой, и
-- проверка по базе показала два разных промаха в чтении таблицы:
--   * УПД 003/2026-0062105 (id 10776): «850 шт × 29,28» приехало как
--     qty = 3, price = 850 — количество съехало на разметку заголовка (графа
--     «Количество» идёт под номером 3), а цена подхватила настоящее количество;
--   * УПД 1708/10 (id 10763): наименования занимают по 2–3 печатных строки, и
--     числа каждой позиции получили наименование соседней; одна позиция
--     пропала совсем.
-- Отдельно, на фото-пути, УПД 848 дал перестановку qty и price местами — её
-- арифметика поймать не может (произведение от перестановки не меняется),
-- поэтому в коде добавлено мягкое предупреждение, а здесь — правило чтения.
--
-- Формулировки намеренно осторожные. Цена хранится как numeric(18,4), и
-- 65.4918 — законное значение, поэтому «у цены не больше двух знаков» писать
-- нельзя: необычная точность объявлена поводом перепроверить расположение
-- чисел, а не основанием менять графы местами. По той же причине служебная
-- строка опознаётся по положению и полной последовательности номеров, а не по
-- отдельному значению 3 или 4 — такие числа в товарной строке законны.
--
-- Вся редакция v11 копируется дословно (INSERT ... SELECT над содержимым из
-- БД), добавляется только хвост. Промпт заводится НЕАКТИВНЫМ: выкат ничего не
-- меняет, включение — вручную в Администрирование → Промпты и только после
--   scripts/upd-prompt-ab.ts --base "default v9" --new "default v12"
--   scripts/segment-prompt-ab.ts --dir <фото комплекта> --expected <эталон>
-- Вместе с v12 включатся и накопленные v10 (не копировать ИНН покупателя
-- грузополучателю) и v11 (поле pricing, без UPD_NO_PRICING_V1 ни на что не
-- влияющее) — это учтено в плане выката.
--
-- Откат: 0113_down.sql.

INSERT INTO "prompts" ("doc_kind", "name", "content", "is_active")
SELECT
  'upd',
  'default v12',
  "content" || chr(10) || chr(10) ||
  '# Чтение табличной части: строки и графы' || chr(10) || chr(10) ||
  'Строка с номерами граф «1, 1а, 1б, 2, 2а, 3, 4, 5…» является разметкой заголовка и не является товарной позицией. Определяй её по положению под названиями колонок и по полной последовательности номеров. Отдельные значения 3 или 4 в товарной строке допустимы и сами по себе не являются ошибкой.' || chr(10) || chr(10) ||
  'Одна позиция соответствует одному порядковому номеру в графе 1. Перенесённые на следующую печатную строку части наименования относятся к той же позиции, пока в графе 1 не появился новый номер. Числа связывай с наименованием из того же горизонтального блока. Пустые, служебные и итоговые строки в items не добавляй. Если указано «Всего наименований», сверь с ним количество items.' || chr(10) || chr(10) ||
  'Для УПД и счёта-фактуры qty читается из графы 3, price — из графы 4. Привязывай значения по заголовкам и вертикальным границам колонок. Не меняй значения местами только из-за количества знаков после запятой: цена может иметь более двух знаков. Необычная точность — повод повторно проверить расположение чисел на изображении.',
  false
FROM "prompts"
WHERE "doc_kind" = 'upd' AND "name" = 'default v11';
