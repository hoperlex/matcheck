-- Кнопка «Распознать повторно»: состояние повтора, режим разбора, позиция
-- документа в пакете и право роли на запуск.
--
-- Зачем каждая колонка.
--
-- 1. source_documents.reparse — состояние ручного повтора ВМЕСТЕ со снимком
--    того, что было до попытки. Снимок нужен не для истории, а для отката:
--    маршрут к моменту разбора уже сменил статус и обнулил second_pass, и без
--    снимка неудачный повтор оставил бы документ хуже, чем он был. Отдельная
--    колонка, а не parse_error_details: те перезаписываются каждым разбором —
--    ровно та причина, по которой рядом живёт second_pass.
--
-- 2. source_documents.parse_mode — чем документ разобран в последний раз
--    (ParseMode из worker.ts). Повтор обязан пойти ТЕМ ЖЕ путём: иначе М-15
--    уедет на УПД-промпт, а логический УПД, собранный из страниц комплекта, —
--    на разбор всего файла целиком, склеив 5/15/4 накладных в один документ.
--    Историческим записям остаётся NULL — для них режим выводится из реестра
--    импорта (bundle_import_items.detected_kind) и типа документа.
--
-- 3. source_documents.batch_index — позиция документа в пакете накладных
--    (индекс в parsed.documents у parseWaybillBatch). Постоянная привязка
--    результата повтора к строке. Сопоставление по номеру для этого не годится:
--    неверно распознанный номер — ровно тот случай, ради которого повтор и
--    запускают, и по нему документ бы не нашёлся.
--
-- 4. role_page_permissions.can_reparse — новое действие матрицы. Отдельное от
--    can_edit: правка полей документа и повторный прогон через модель
--    различаются и по цене, и по последствиям.
--
-- Про UPDATE ниже. В КАТАЛОГЕ право не выдано никому: дефолт обязан повторять
-- сегодняшний доступ, а маршрут новый. Роль «Мониторинг» получает его не
-- дефолтом, а строкой матрицы — той самой, которой администратор уже открыл ей
-- раздел «Документы» (в боевой БД у monitor × documents.list стоят
-- view/create/edit/delete). Дописываем в неё ещё одну галочку, чтобы кнопка
-- работала сразу, а не после ручного захода в «Роли».
--
-- Условие максимально узкое: одна роль, одна страница. Прочие строки не
-- трогаются, у них остаётся DEFAULT false.
--
-- Важно: при PERMISSIONS_ENFORCE=0 матрица не читается вовсе, и до включения
-- флага повтор доступен только администратору (он вне матрицы). Это не побочный
-- эффект миграции, а свойство самого флага.

ALTER TABLE "source_documents" ADD COLUMN IF NOT EXISTS "reparse" jsonb;
