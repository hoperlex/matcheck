-- Каким промптом разобрана накладная.
--
-- Зачем. У накладных появился второй промпт — форма 1-Т (Госкомстат №78, ОКУД
-- 0345009), и файл может уйти к нему вместо активного промпта ТН-2116. Повторный
-- разбор («распознать заново») обязан идти ТЕМ ЖЕ путём: он находит «свой»
-- документ по batch_index — позиции в ответе модели, — и разбор другим промптом
-- вернёт другой набор документов, где под тем же индексом окажется чужая
-- накладная. Результат уехал бы в неверную строку.
--
-- NULL — «разобрано активным промптом накладных», то есть всё, что было до этой
-- миграции, и всё, что и дальше пойдёт обычным путём.
--
-- НЕДЕСТРУКТИВНО: только новая nullable-колонка.

ALTER TABLE "source_documents"
  ADD COLUMN IF NOT EXISTS "waybill_prompt_kind" text;

COMMENT ON COLUMN "source_documents"."waybill_prompt_kind" IS
  'Вид промпта, которым разобрана накладная (transport_waybill_1t). NULL — активный промпт накладных.';
