-- Время последней неудачной попытки входа.
--
-- Зачем. failed_login_count копился вечно: он обнулялся только успешным входом
-- или админским сбросом пароля. Из-за этого ошибки, разделённые неделями,
-- складывались в одну «серию» — пользователь с четырьмя опечатками сегодня
-- упирался в потолок, набранный ещё в прошлом месяце, и получал блокировку
-- аккаунта на полчаса.
--
-- Что даёт колонка. Серия неудач протухает после часа без единой ошибки:
-- следующая неудача начинает счёт заново (см. routes/auth.ts). Это именно
-- TTL бездействия, а не скользящее окно — при попытке раз в 59 минут счётчик
-- продолжит расти. Для нашей задачи этого достаточно: живой человек, ошибшийся
-- дважды за день, стартует с нуля, а непрерывный перебор по-прежнему тормозится.
--
-- Счётчик теперь влияет ТОЛЬКО на длину паузы перед ответом. Блокировки
-- аккаунта не существует: верные логин и пароль пускают всегда, поэтому
-- locked_until больше не выставляется (колонка оставлена, её продолжает
-- обнулять админский сброс пароля).
--
-- Аддитивно и nullable: старый образ продолжает работать на новой схеме.

ALTER TABLE "users"
  ADD COLUMN IF NOT EXISTS "last_failed_login_at" timestamptz;
--> statement-breakpoint
-- Бэкфилл для тех, у кого серия уже накоплена. Без отметки времени первая же
-- неудача после выката считалась бы началом новой серии — счётчик сбросился бы
-- в 1, а накопленное значение осталось бы висеть в БД мёртвым грузом. Ставим
-- заведомо старую дату: серия считается протухшей, пауза начинается с базовой.
UPDATE "users"
   SET "last_failed_login_at" = now() - interval '1 day'
 WHERE "failed_login_count" > 0
   AND "last_failed_login_at" IS NULL;
