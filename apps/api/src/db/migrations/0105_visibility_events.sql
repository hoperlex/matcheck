-- Журнал переходов видимости документа для планшета.
--
-- Зачем отдельный механизм, а не existing deletedIds.
--
-- Сейчас /sync отдаёт в deletedIds только физически удалённые записи
-- (entity_deletions). Но документ может ПЕРЕСТАТЬ БЫТЬ ВИДИМЫМ, оставаясь в
-- базе: ушёл из parsed при повторном разборе, потерял объект или дату, попал в
-- группу, где соседний документ ещё обрабатывается. Планшет о таком не узнаёт
-- никогда — дельта отбирает по updated_at, а у скрытого документа он не менялся.
-- Инспектор продолжает видеть машину, которой больше нет, и принимает по
-- устаревшему составу.
--
-- Почему журнал, а не вычисление на лету. Вычислить «что пропало с прошлого
-- since» можно только сравнив два снимка, а второго снимка ни у сервера, ни у
-- клиента нет. Планшет уходит в офлайн на дни: к моменту возврата документ мог
-- скрыться и снова появиться. Журнал переживает офлайн любой длины, вычисление —
-- нет.
--
-- НЕДЕСТРУКТИВНО: только новая таблица.

CREATE TABLE IF NOT EXISTS "source_document_visibility_events" (
  "id" bigserial PRIMARY KEY,

  -- Без FK. Событие «скрыт» обязано пережить удаление документа: планшет,
  -- вернувшийся из офлайна, должен узнать об исчезновении, даже если запись
  -- уже вычищена. Каскад стёр бы событие ровно в этом случае.
  "source_document_id" uuid NOT NULL,

  -- Куда перешёл документ. 'hidden' — снять с планшета, 'visible' — показать.
  "visibility" text NOT NULL,

  -- Объект нужен для фильтра инспектора КПП: он получает дельту только по
  -- своему объекту, и события чужих объектов ему отдавать незачем. NULL
  -- допустим — документ мог остаться без объекта, именно поэтому и скрылся.
  "site_id" uuid,

  -- Группа, из-за которой произошёл переход. Заполнена, когда документ скрыт
  -- не сам по себе, а вместе со всей машиной: по ней ищут «все члены группы»
  -- при разборе инцидента.
  "group_id" uuid,

  -- Почему. Значение свободное, читается человеком в логах и в поддержке.
  "reason" text,

  "created_at" timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT "source_document_visibility_events_visibility_check"
    CHECK ("visibility" IN ('hidden', 'visible'))
);

-- Основной индекс выдачи: «что изменилось после since», с отбором по объекту.
-- Порядок колонок под запрос дельты: created_at первым, потому что since —
-- всегда диапазон, а site_id — равенство или отсутствие фильтра.
CREATE INDEX IF NOT EXISTS "source_document_visibility_events_cursor_idx"
  ON "source_document_visibility_events" ("created_at", "id");

-- Для «покажи последнее состояние документа»: схлопывание hide→show до
-- актуального конечного значения делается по этому индексу.
CREATE INDEX IF NOT EXISTS "source_document_visibility_events_document_idx"
  ON "source_document_visibility_events" ("source_document_id", "created_at" DESC);

CREATE INDEX IF NOT EXISTS "source_document_visibility_events_site_idx"
  ON "source_document_visibility_events" ("site_id", "created_at")
  WHERE "site_id" IS NOT NULL;
