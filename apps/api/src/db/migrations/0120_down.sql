-- Откат 0120: убирает промпт «upd / default v16».
--
-- Не удаляем активный или уже использованный промпт: такой откат стёр бы связь
-- llm_calls с фактическим текстом распознавания, и объяснить прошлые разборы
-- стало бы нечем. Если v16 успели включить, сначала верните активность прежней
-- версии кнопкой в Администрирование → Промпты — вид upd не должен остаться
-- без активной записи.
DELETE FROM "prompts" p
WHERE p."doc_kind" = 'upd'
  AND p."name" = 'default v16'
  AND p."is_active" = false
  AND NOT EXISTS (SELECT 1 FROM "llm_calls" c WHERE c."prompt_id" = p."id");
