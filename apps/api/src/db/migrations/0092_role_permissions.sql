-- Матрица прав ролей: «роль × страница × действие» (Просмотр/Создавать/
-- Редактировать/Удалять), редактируемая админом во вкладке «Роли».
--
-- Что это меняет в поведении: НИЧЕГО в день выката. Таблица создаётся пустой,
-- а пустая строка означает «как в дефолте». Дефолт живёт в коде
-- (packages/contracts/src/permissions.ts, DEFAULT_MATRIX) и в точности
-- повторяет сегодняшние права роли. Применение матрицы включается отдельным
-- флагом PERMISSIONS_ENFORCE, по умолчанию выключенным.
--
-- Почему БЕЗ seed. Строка здесь — это OVERRIDE, отклонение от дефолта, а не
-- «текущее значение». Засеять таблицу дефолтами значило бы заморозить их
-- слепком на день выката: любое последующее изменение DEFAULT_MATRIX в коде
-- (новая страница, изменившийся allow-list роута) не подхватилось бы, и
-- расхождение проявилось бы молча. Отсутствие строки — это «спроси у кода».
--
-- Почему 4 boolean-колонки, а не строка-на-действие и не битовая маска.
-- Набор действий закрыт и зафиксирован продуктом. Строка-на-действие дала бы
-- ~500 строк вместо ~92 и превратила бы правку одной ячейки в отдельную
-- сущность. Маска компактна, но нечитаема, а чинить эту таблицу при инциденте
-- «менеджер не может работать» придётся руками в psql:
--   UPDATE role_page_permissions SET can_edit = true
--     WHERE role = 'manager' AND page_id = 'documents.list';
--
-- Почему admin запрещён CHECK'ом. Роль admin обходит матрицу целиком — иначе
-- админ способен снять себе доступ к самой вкладке «Роли» и остаться без
-- пути назад (чинить пришлось бы psql'ем на бою). Констрейнт — второй рубеж
-- к проверке в API: строку для admin нельзя создать даже вручную.
--
-- page_id намеренно БЕЗ внешнего ключа и без таблицы-каталога: каталог
-- страниц меняется вместе с релизом кода (новая вкладка = новый роут =
-- деплой), и вторая копия в БД только расходилась бы с ним. Неизвестные
-- page_id при чтении игнорируются, отсутствующие берутся из дефолта — то
-- есть добавление страницы в коде не требует миграции.

CREATE TABLE IF NOT EXISTS "role_page_permissions" (
  "role"       "user_role"  NOT NULL,
  "page_id"    varchar(64)  NOT NULL,
  "can_view"   boolean      NOT NULL DEFAULT false,
  "can_create" boolean      NOT NULL DEFAULT false,
  "can_edit"   boolean      NOT NULL DEFAULT false,
  "can_delete" boolean      NOT NULL DEFAULT false,
  "updated_at" timestamptz  NOT NULL DEFAULT now(),
  "updated_by_user_id" uuid REFERENCES "users"("id") ON DELETE SET NULL,
  CONSTRAINT "role_page_permissions_pkey" PRIMARY KEY ("role", "page_id"),
  CONSTRAINT "role_page_permissions_no_admin" CHECK ("role" <> 'admin')
);
