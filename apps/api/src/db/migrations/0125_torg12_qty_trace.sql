-- След правила количества по графам товарной накладной ТОРГ-12
-- (domain/edo/torg12-qty).
--
-- Зачем отдельная колонка, а не qty_repair. Правила разные: то восстанавливает
-- количество из арифметики строки и для накладной БЕЗ ЦЕН не работает вовсе,
-- а это считает количество по графам бланка («в одном месте» × «мест»). У них
-- разные режимы рубильников и разные наборы полей в записи; общий след нельзя
-- было бы ни прочитать однозначно, ни откатить по частям.
--
-- Содержимое (jsonb): ruleVersion, mode, detectedAt, generation, docVersion и
-- entries[] с полями state ('observed' | 'applied'), row, itemId, kind
-- ('qty_missing' | 'mass_as_qty'), qtyFrom, qtyTo, qtyPerPlace, places,
-- massNetKg, unit.
--
-- Колонка СЛУЖЕБНАЯ: веб её не читает, в публичные контракты не входит, на
-- карточки, экраны и планшет не влияет.
--
-- НЕДЕСТРУКТИВНО: только новая nullable-колонка, существующие строки читаются
-- как NULL («правило по этому документу не работало»).

ALTER TABLE "source_documents"
  ADD COLUMN IF NOT EXISTS "torg12_qty" jsonb;

COMMENT ON COLUMN "source_documents"."torg12_qty" IS
  'След правила количества по графам ТОРГ-12: кандидаты и применённые правки с исходными значениями и версией разбора. NULL — кандидатов не было. Служебное поле, UI не читает.';
