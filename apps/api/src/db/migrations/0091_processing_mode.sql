-- Режим обработки входного файла: распознавать или только сохранить.
--
-- Зачем. В форме поставки появилась вторая зона — «Дополнительные документы»
-- (сертификаты, паспорта качества, спецификации, акты). Файл оттуда не
-- классифицируется и не распознаётся вовсе: он просто лежит в S3 и виден
-- менеджеру в карточке поставки. Раньше такой файл проходил весь путь
-- распознавания впустую и оседал в списке пустым черновиком.
--
-- Почему колонка, а не новый статус. Статус отвечает на вопрос «чем кончилось»
-- (accepted → created / skipped / failed), а режим — на вопрос «что вообще
-- собирались делать», и он известен уже в момент приёма, до всякой обработки.
-- Смешивать их значило бы терять причину: у skipped их теперь две — «человек
-- сказал не распознавать» и «тип определить не удалось».
--
-- DEFAULT 'auto' обязателен: у всех исторических строк режим ровно такой, и
-- старые клиенты (мобильное приложение, прежние сборки веба) шлют файлы одной
-- зоной, то есть тоже auto.

ALTER TABLE "bundle_import_items"
  ADD COLUMN IF NOT EXISTS "processing_mode" text NOT NULL DEFAULT 'auto';
