-- УПД-промпт v15: дробное количество и цена, которую путают со стоимостью.
--
-- Зачем. A/B v13 против v14 на корпусе показал, что главный класс ошибок
-- («съехавшие колонки») v14 не вылечила, а сместила. Скан 1697.pdf, бланк
-- читается глазами однозначно: количество 76,032 м³, цена 6 846,72, стоимость
-- без налога 520 569,92.
--   * v13 вернула price = 76032 — это КОЛИЧЕСТВО, прочитанное как целое:
--     запятая принята за разделитель тысяч;
--   * v14 вернула price = 520569.92 — это графа 5, стоимость всей позиции.
-- Обе версии не прочитали цену вовсе. Тот же почерк у боевого № 6583:
-- «52,000 м²» стало ценой 52000.
--
-- Отсюда два правила, которых не было ни в одной версии:
--   1. в графе 3 запятая ВСЕГДА отделяет дробную часть (76,032 = 76.032),
--      разделитель тысяч в бланке — пробел. Прочитав количество в тысячу раз
--      больше, модель почти наверняка положит его не в ту графу;
--   2. цена, равная стоимости строки (графа 5 или 9), — признак взятой не той
--      колонки. Совпадать они могут только при количестве, равном единице.
-- Плюс арифметическая самопроверка перед ответом: qty × price должно сойтись с
-- графой 5. Соотношение упомянуто ещё в v13, но как справочное; здесь оно
-- сформулировано как действие — «не сошлось в разы, перечитай графы 3 и 4».
--
-- Почему новая версия, а не правка v14. На v14 уже ссылаются строки llm_calls
-- (прогоны A/B), и правка текста сделала бы прошлые отчёты необъяснимыми.
-- v14 остаётся в таблице неактивной.
--
-- Промпт заводится НЕАКТИВНЫМ. Включение — вручную в Администрирование →
-- Промпты, и только после
--   scripts/upd-prompt-ab.ts --base "default v13" --new "default v15" --details
--
-- Откат: 0119_down.sql.

INSERT INTO "prompts" ("doc_kind", "name", "content", "is_active")
SELECT
  'upd',
  'default v15',
  "content" || chr(10) || chr(10) ||
  '# Дробное количество: запятая — это НЕ разделитель тысяч' || chr(10) || chr(10) ||
  'В графе 3 количество печатается с дробной частью через запятую: «76,032 м³» — это 76.032, «100,000» — это 100, «52,000 м²» — это 52. Разделителем тысяч в российском бланке служит ПРОБЕЛ («7 371,80»), поэтому запятая не превращает 76,032 в 76032 никогда. Ошибка здесь не остаётся одинокой: прочитав количество в тысячу раз больше, ты почти наверняка сдвинешь и остальные графы — настоящая цена окажется непрочитанной, а её место займёт количество или стоимость.' || chr(10) || chr(10) ||
  '# Цена — это графа 4, а не стоимость позиции' || chr(10) || chr(10) ||
  'price берётся ТОЛЬКО из графы 4 «Цена (тариф) за единицу измерения». Если число, которое ты собираешься вернуть как price, совпадает со значением графы 5 («Стоимость … без налога — всего») или графы 9 («… с налогом — всего») той же строки — ты взял не ту колонку. Цена за единицу равна стоимости всей позиции лишь тогда, когда количество равно единице; во всех остальных случаях это разные числа, и путать их нельзя.' || chr(10) || chr(10) ||
  'Перед ответом проверь арифметикой: qty × price должно сойтись с графой 5 с точностью до копеек округления. Разошлось в разы — значит графа 3 или графа 4 прочитана неверно. Перечитай обе по вертикальным границам колонок и НЕ подгоняй числа друг под друга: подогнанный ответ выглядит правдоподобно и потому опаснее пустого поля.',
  false
FROM "prompts"
WHERE "doc_kind" = 'upd' AND "name" = 'default v14';
--> statement-breakpoint

DO $$
DECLARE
  v15_count int;
  v15_extends_v14 int;
  v15_has_rules int;
  v15_active int;
  active_cnt int;
  active_name text;
BEGIN
  SELECT count(*) INTO v15_count
    FROM prompts WHERE doc_kind = 'upd' AND name = 'default v15';
  IF v15_count <> 1 THEN
    RAISE EXCEPTION 'Ожидался ровно один промпт «upd / default v15», найдено %. Проверьте наличие default v14.', v15_count;
  END IF;

  SELECT count(*) INTO v15_extends_v14
    FROM prompts v15
    JOIN prompts v14 ON v14.doc_kind = 'upd' AND v14.name = 'default v14'
   WHERE v15.doc_kind = 'upd' AND v15.name = 'default v15'
     AND position(v14.content in v15.content) = 1
     AND v15.content <> v14.content;
  IF v15_extends_v14 <> 1 THEN
    RAISE EXCEPTION 'default v15 не является дословным расширением default v14.';
  END IF;

  -- Оба правила проверяются вместе: поодиночке они не закрывают случай.
  -- Прочитав «76,032» как 76032, модель обязана куда-то деть настоящую цену —
  -- и кладёт туда стоимость строки, что и сделала v14.
  SELECT count(*) INTO v15_has_rules
    FROM prompts
   WHERE doc_kind = 'upd' AND name = 'default v15'
     AND content LIKE '%76,032 м³» — это 76.032%'
     AND content LIKE '%Разделителем тысяч в российском бланке служит ПРОБЕЛ%'
     AND content LIKE '%совпадает со значением графы 5%'
     AND content LIKE '%qty × price должно сойтись с графой 5%';
  IF v15_has_rules <> 1 THEN
    RAISE EXCEPTION 'В default v15 отсутствуют правила про дробное количество или подмену цены стоимостью.';
  END IF;

  SELECT count(*) INTO v15_active
    FROM prompts WHERE doc_kind = 'upd' AND name = 'default v15' AND is_active = true;
  IF v15_active <> 0 THEN
    RAISE EXCEPTION 'default v15 не должен активироваться миграцией.';
  END IF;

  SELECT count(*) INTO active_cnt
    FROM prompts WHERE doc_kind = 'upd' AND is_active = true;
  IF active_cnt <> 1 THEN
    RAISE EXCEPTION 'Ожидался ровно один активный промпт «upd», найдено %.', active_cnt;
  END IF;

  SELECT name INTO active_name
    FROM prompts WHERE doc_kind = 'upd' AND is_active = true;
  IF active_name = 'default v15' THEN
    RAISE EXCEPTION 'default v15 не должен становиться активным в миграции.';
  END IF;
END $$;
