-- Индекс на живые refresh-токены сессии.
--
-- Зачем. revokeBySessionId гасит все неотозванные токены сессии по session_id
-- (logout, инвалидация при reuse-detection, смена пароля), но индекса на
-- session_id у refresh_tokens не было вовсе — только PK и unique по token_hash.
-- На проде таблица разрослась до ~135 тыс. строк / ~57 МБ (растёт на строку с
-- каждой ротацией, ретенции нет), и каждый такой вызов сканировал её целиком.
--
-- Частичный (WHERE revoked_at IS NULL) — потому что запрос всегда ищет только
-- живые токены, а отозванные составляют почти весь объём таблицы. Индекс от
-- этого на порядок меньше и не растёт вместе с историей.
--
-- Ветке идемпотентного replay (domain/auth/refresh.ts) этот индекс НЕ нужен:
-- она ходит за строкой-заменой по первичному ключу.
--
-- НЕДЕСТРУКТИВНО: только CREATE INDEX IF NOT EXISTS, данные не меняются.
--
-- ПОРЯДОК ВЫКАТА (важно: таблица в горячем пути логина и refresh):
--   1) СНАЧАЛА прогнать online-index runner (scripts/create-indexes-online.ts) —
--      он строит этот индекс CONCURRENTLY, не блокируя выдачу токенов.
--   2) ПОТОМ обычный деплой: migrate.ts выполнит этот файл, и CREATE INDEX
--      IF NOT EXISTS увидит готовый индекс → мгновенный no-op без блокировки.
-- Если runner не запускался, файл создаст индекс обычным CREATE INDEX — это
-- SHARE-лок на время построения, то есть пауза в выдаче и ротации токенов.

CREATE INDEX IF NOT EXISTS "refresh_tokens_session_active_idx" ON "refresh_tokens" ("session_id") WHERE "revoked_at" IS NULL;
