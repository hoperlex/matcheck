-- Закрывает строку реестра, повисшую после удаления накладной ТТН 16531.
--
-- Документ удалили 19.08 (запись в entity_deletions), а строка принятого файла
-- осталась с resolved_at IS NULL — и список показывал удалённый документ снова,
-- строкой «в очереди», без кнопок повтора и удаления. Причина — в признаке
-- связи: файл ушёл в дочерний waybill-пакет, документ создавался уже там, и
-- прямых ссылок (stub_document_id, created_document_ids) у строки нет.
--
-- Код исправлен в этом же выкате (closeRegistryRowsForDeletedDocument получил
-- третью ветку — по input_s3_key), но фикс работает только для БУДУЩИХ
-- удалений. Эту строку он не тронет: документа уже нет, закрывать её некому.
--
-- ТОЧЕЧНАЯ ПРАВКА ДАННЫХ, не изменение схемы. Массово такие строки не закрыть:
-- отличить «файл повис из-за удалённого документа» от «файл честно ждёт
-- разбора» в SQL нечем, а ошибка второго рода спрячет от менеджера непринятые
-- документы.
--
-- resolved_by_user_id намеренно остаётся NULL: строку закрывает миграция, а не
-- человек. Функция заполняет это поле только при реальном удалении.
DO $$
DECLARE
  affected integer;
BEGIN
  UPDATE "bundle_import_items"
     SET "resolved_at" = now(),
         "reason"      = 'документ по файлу удалён',
         "updated_at"  = now()
   WHERE "id" = '074b0330-3dbe-46d9-a3bd-62629dbf76f7'
     AND "source_filename" = 'ТТН 16531.pdf'
     AND "resolved_at" IS NULL;

  GET DIAGNOSTICS affected = ROW_COUNT;

  -- 0 — нормальный исход: строку могли закрыть вручную до выката, либо
  -- миграция уже применялась. Больше одной строки невозможно: отбор по PK.
  IF affected = 0 THEN
    RAISE NOTICE '0111: строка уже закрыта или не найдена — правка не требуется';
  ELSE
    RAISE NOTICE '0111: закрыта % строка реестра', affected;
  END IF;
END $$;
