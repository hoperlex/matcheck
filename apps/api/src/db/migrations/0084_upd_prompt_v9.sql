-- УПД-промпт v9: грузополучатель (графа 4).
--
-- Зачем. В списке Документов нужны три стороны документа — покупатель,
-- грузополучатель, поставщик. Продавец и покупатель извлекались и раньше,
-- грузополучателя не просил ни один промпт УПД (v1…v8), хотя в тексте формы
-- он есть всегда.
--
-- Что меняется относительно v8: РОВНО одна добавленная строка в разделе
-- «Заголовок документа». Остальной текст копируется из v8 бит-в-бит — потому
-- и делается через replace() над содержимым из БД, а не ручным переписыванием
-- 200 строк: так исключены незаметные расхождения в пробелах и формулировках,
-- из-за которых поехало бы распознавание уже работающих полей.
--
-- Промпт заводится НЕАКТИВНЫМ. Активация — вручную в Администрирование →
-- Промпты, и только после прогона scripts/upd-prompt-ab.ts: он сверяет v8 и v9
-- на корпусе docs/debug-upd и показывает, не изменились ли номера, даты, суммы
-- и позиции. До активации прод продолжает работать на v8.
--
-- Откат: 0084_down.sql (удаляет v9; активной он к тому моменту быть не должен).

INSERT INTO "prompts" ("doc_kind", "name", "content", "is_active")
SELECT
  'upd',
  'default v9',
  replace(
    "content",
    '- recipient:  { inn, kpp, name } — покупатель.',
    '- recipient:  { inn, kpp, name } — покупатель.' || chr(10) ||
    '- consignee:  { inn, kpp, name } — грузополучатель (графа 4). ИНН там обычно не печатают — тогда inn: null, а name заполни. Если написано «он же» — это ПОКУПАТЕЛЬ, повтори recipient.'
  ),
  false
FROM "prompts"
WHERE "doc_kind" = 'upd' AND "name" = 'default v8';
--> statement-breakpoint
-- Гейт: миграция идёт одной транзакцией, поэтому непройденная проверка
-- откатывает и вставку. Ловим два случая: v8 не найден (тогда INSERT ничего
-- не вставил) и якорная строка не совпала (тогда replace вернул текст без
-- consignee, и v9 был бы копией v8).
DO $$
DECLARE
  v9_count int;
  v9_ok int;
BEGIN
  SELECT count(*) INTO v9_count FROM prompts WHERE doc_kind = 'upd' AND name = 'default v9';
  IF v9_count <> 1 THEN
    RAISE EXCEPTION 'Ожидался ровно один промпт «default v9», найдено %. Проверьте, что «default v8» есть в таблице prompts.', v9_count;
  END IF;

  SELECT count(*) INTO v9_ok
    FROM prompts
   WHERE doc_kind = 'upd' AND name = 'default v9' AND content LIKE '%consignee%';
  IF v9_ok <> 1 THEN
    RAISE EXCEPTION 'В промпте «default v9» нет строки про consignee — якорная строка v8 не совпала, replace ничего не заменил.';
  END IF;
END $$;
