--
-- Формулировка v9 «ИНН там обычно не печатают — тогда inn: null» оказалась
-- слишком мягкой: слово «обычно» модель трактует как разрешение подставить
-- реквизиты, если она их «знает» из графы 6. v10 говорит это запретом, а
-- законное исключение («он же») называет явно — иначе новое правило
-- противоречило бы старому.
--
-- Что меняется относительно v9: РОВНО одна строка — та, что v9 добавил к v8.
-- Остальной текст копируется из v9 бит-в-бит через replace() над содержимым из
-- БД, а не переписывается руками: так исключены незаметные расхождения, из-за
-- которых поехало бы распознавание уже работающих полей.
--
-- Промпт заводится НЕАКТИВНЫМ. Активация — вручную в Администрирование →
-- Промпты, и только после прогонов:
