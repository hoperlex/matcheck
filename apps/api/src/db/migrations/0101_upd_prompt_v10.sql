--
-- Зачем. Промпт v9 включили на бою 14.08 в 12:56, и он сразу показал дефект:
-- модель подставляет ИНН и КПП ПОКУПАТЕЛЯ грузополучателю, хотя графа 4 формы
-- 1137 реквизитов не содержит вовсе — там печатают только наименование и адрес.
-- Документ 1736 получил «ООО "АЛЬЯНС"» с ИНН и КПП компании «СУ-10» (1 случай
-- из 3; у двух других грузополучатель и правда СУ-10, поэтому совпадение ИНН
-- прошло незамеченным). Для пользователя это чужой ИНН второй строкой в колонке
