-- Гейт. Проверка «в тексте есть consignee» здесь БЕСПОЛЕЗНА, в отличие от 0084:
-- там v9 порождался из v8, где слова consignee не было, и его появление
-- доказывало, что replace() сработал. Тут исходник — сам v9, и это слово в нём
-- уже есть: при несовпавшем якоре replace() вернул бы текст без изменений, v10
-- стал бы точной копией v9, а такая проверка осталась бы зелёной.
--
-- Поэтому доказательством служит РАЗЛИЧИЕ текстов плюс наличие новой фразы.
DO $$
DECLARE
  v10_count int;
  v10_changed int;
  v10_has_rule int;
  v10_active int;
BEGIN
  SELECT count(*) INTO v10_count FROM prompts WHERE doc_kind = 'upd' AND name = 'default v10';
  IF v10_count <> 1 THEN
    RAISE EXCEPTION 'Ожидался ровно один промпт «upd / default v10», найдено %. Проверьте, что «default v9» есть в таблице prompts.', v10_count;
  END IF;

  SELECT count(*) INTO v10_changed
    FROM prompts v10
    JOIN prompts v9 ON v9.doc_kind = 'upd' AND v9.name = 'default v9'
   WHERE v10.doc_kind = 'upd' AND v10.name = 'default v10' AND v10.content <> v9.content;
  IF v10_changed <> 1 THEN
    RAISE EXCEPTION 'Промпт «default v10» дословно совпал с «default v9» — якорная строка не найдена, replace ничего не заменил.';
  END IF;

  SELECT count(*) INTO v10_has_rule
    FROM prompts
   WHERE doc_kind = 'upd' AND name = 'default v10'
     AND content LIKE '%ТОЛЬКО если они напечатаны в самой графе 4%';
  IF v10_has_rule <> 1 THEN
    RAISE EXCEPTION 'В промпте «default v10» нет правила про реквизиты графы 4 — подставился не тот текст.';
  END IF;

  SELECT count(*) INTO v10_active
    FROM prompts
   WHERE doc_kind = 'upd' AND name = 'default v10' AND is_active = true;
  IF v10_active <> 0 THEN
    RAISE EXCEPTION 'Промпт «default v10» не должен быть активным сразу после миграции.';
  END IF;
END $$;
