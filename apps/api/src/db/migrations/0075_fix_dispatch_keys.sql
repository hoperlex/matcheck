-- Починка ключей диспетчеризации в job_outbox.
--
-- BullMQ отвергает custom job id с двоеточием («Custom Id cannot contain :»),
-- поэтому задания с ключами вида `doc:<uuid>:parse:0` не доставлялись: строки
-- копили attempts, а документы висели в статусе queued. Разделитель заменён на
-- `~` (см. dispatchKeyOf в domain/jobs/job-outbox.ts).
--
-- Здесь переписываем накопившиеся строки на новый формат вместо удаления:
-- задание терять нельзя, это и есть смысл outbox. Счётчик попыток и время
-- следующей попытки сбрасываем, чтобы consumer забрал их сразу, а не ждал
-- накопленный экспоненциальный backoff (после 6 неудач это уже минуты).
--
-- Конфликты по новому ключу исключены: старый и новый форматы взаимно
-- однозначны, а уникальный индекс на dedupe_key уже существует.

UPDATE job_outbox
SET dedupe_key = replace(dedupe_key, ':', '~'),
    attempts = 0,
    next_attempt_at = now(),
    processing_at = NULL,
    last_error = NULL
WHERE dedupe_key LIKE '%:%';

-- Тот же ключ хранится в самом документе — по нему подбор зависших записей
-- находит задание повторно. Рассинхрон оставил бы repair'у шанс поставить
-- ВТОРОЕ задание под другим ключом, то есть распознать документ дважды.
UPDATE source_documents
SET job_id = replace(job_id, ':', '~')
WHERE job_id LIKE 'doc:%:parse:%';
