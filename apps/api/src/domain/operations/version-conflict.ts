/**
 * Версия операции сменилась между проверкой `baseVersion` и записью.
 *
 * Маршрут upsert сверяет `baseVersion` с `existing.version`, прочитанным ВНЕ
 * транзакции. Пока UPDATE версию не проверял, конкурент (например, отвязка
 * документа с удалением его строк) мог зафиксироваться между этими шагами, и
 * upsert записывал поверх старый список позиций — удалённые строки
 * возвращались. Теперь UPDATE идёт с условием `version = baseVersion`, а ноль
 * задетых строк при сменившейся версии превращается в эту ошибку.
 *
 * На верхнем уровне маршрута — тот же 409 `conflict`, что отдаёт ранняя
 * проверка: клиенты (планшет, очередь портала) отличать их не должны.
 */
export class VersionConflictError extends Error {
  constructor(
    readonly serverVersion: number,
    /** id операции — для DTO в ответе 409 (в теле upsert id необязателен). */
    readonly entityId: string,
  ) {
    super('version_conflict');
  }
}
