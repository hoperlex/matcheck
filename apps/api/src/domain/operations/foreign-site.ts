/**
 * Инспектор (`inspector_kpp`) работает строго в рамках своего объекта: он не
 * может ни отредактировать чужую приёмку/отгрузку, ни «перетащить» её к себе.
 *
 * Раньше upsert безусловно проставлял `siteId` текущего пользователя, поэтому
 * любой клиент, у которого локально остались записи чужого объекта (планшет
 * после смены аккаунта, веб-PWA с непустой очередью в IndexedDB), при
 * переотправке физически переносил их на свой объект. Инцидент 2026-07:
 * 287 приёмок и 141 отгрузка объекта ЗИЛ33 уехали на TEST.
 *
 * Ошибка кидается ИЗ ТРАНЗАКЦИИ update-хелпера, когда `UPDATE ... WHERE id = ?
 * AND site_id = ?` не задел ни одной строки (объект записи сменился между
 * чтением `existing` и апдейтом), и на верхнем уровне маршрута превращается
 * в 403 `foreign_site`.
 */
export class ForeignSiteError extends Error {
  constructor() {
    super('foreign_site');
  }
}

export const FOREIGN_SITE_RESPONSE = {
  error: 'foreign_site',
  message: 'Запись другого объекта',
} as const;
