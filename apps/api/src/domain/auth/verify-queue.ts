/**
 * Очередь проверок пароля: ограничивает, сколько bcrypt-сравнений идёт
 * одновременно. Лишние ждут в FIFO-очереди — никто не получает отказ.
 *
 * Зачем очередь, а не rate-limit. На /auth/login нет ни одного ограничителя,
 * способного отказать до проверки пароля: требование — верные логин и пароль
 * пускают ВСЕГДА. Значит каждый запрос доходит до bcrypt (cost 12, ~250 мс),
 * и без ограничителя пачка запросов забивала бы событийный цикл целиком.
 * Очередь растягивает их во времени: медленно, но без 429 в лицо тому, кто
 * ввёл правильный пароль.
 *
 * Чего очередь НЕ делает. bcryptjs — чистый JS и считает в главном потоке, так
 * что суммарный расход CPU она не уменьшает, только сглаживает пик и оставляет
 * зазоры остальным роутам. И backlog не ограничен: при достаточном флуде
 * корректный вход встанет в хвост и будет ждать долго. Ограничить длину
 * очереди значило бы отказывать при переполнении — то есть вернуть тот самый
 * 429. Настоящее решение — ограничение на периметре (Caddy) или вынос bcrypt
 * в worker thread; и то и другое за рамками этой задачи.
 */

// Четыре — компромисс: заметно меньше, чем может прийти в пике, но достаточно,
// чтобы утренний вход целого объекта не выстроился в цепочку по одному.
const MAX_CONCURRENT = 4;

let active = 0;
const waiting: Array<() => void> = [];

/**
 * Пропускает `task` через очередь. Разрешение освобождается в finally, поэтому
 * упавшая проверка не подвешивает очередь навсегда.
 */
export async function withVerifySlot<T>(task: () => Promise<T>): Promise<T> {
  // Разрешение НЕ пересчитывается после пробуждения, а передаётся из рук в
  // руки. Иначе между resolve() ожидающего и продолжением его корутины
  // (микротаска!) успел бы влезть новый вызов: он синхронно увидел бы
  // освободившийся слот, занял его, и лимит оказался бы превышен на единицу.
  if (active >= MAX_CONCURRENT) {
    await new Promise<void>((resolve) => waiting.push(resolve));
  } else {
    active += 1;
  }
  try {
    return await task();
  } finally {
    const next = waiting.shift();
    if (next) next();
    else active -= 1;
  }
}

/** Только для тестов: сколько задач сейчас ждёт очереди. */
export function verifyQueueDepth(): number {
  return waiting.length;
}
