/**
 * Страница списка документов, которая не разрывает поставку.
 *
 * Одна загрузка — это машина: пять УПД, приехавшие вместе, менеджер читает как
 * одну поставку. Пока страница резалась по документам, такая пятёрка могла
 * разъехаться между страницами: на первой три документа, на второй два, и
 * связь между ними терялась. Клиентская кластеризация тут бессильна — она
 * видит только загруженные строки.
 *
 * Поэтому окно страницы считается по ПОСТАВКАМ: строки уже отсортированы
 * сервером, поставки собираются по первому появлению, и целая поставка
 * попадает на ту страницу, где она началась. Из-за этого на странице выходит
 * не ровно `pageSize` строк, а «около»: у самой большой боевой поставки
 * одиннадцать документов, так что разброс невелик.
 *
 * Почему первое появление = правильное место поставки. Строки приходят уже
 * упорядоченными (по сумме, дате, статусу — как выбрал пользователь), значит
 * первой из своей поставки встретится ровно крайняя: самая большая при
 * убывании, самая малая при возрастании. Отдельная сортировка групп не нужна.
 */

/** Строка выдачи: документ или принятый файл, до которого разбор не дошёл. */
export type GroupPagingRow = {
  id: string;
  /** Поставка: корневой пакет. У документа без пакета — он сам. */
  groupId: string;
  kind: 'doc' | 'pending';
};

export type GroupPagingResult<T> = {
  /** Строки запрошенной страницы, в исходном порядке. */
  rows: T[];
  /** Сколько всего страниц получилось при такой упаковке. */
  pageCount: number;
};

/**
 * Режет упорядоченные строки на страницы, не разрывая поставку.
 *
 * `page` — с единицы, как в адресе. Страница за пределами набора даёт пустой
 * список: так же ведёт себя обычный offset.
 */
export function pageOfGroupedRows<T extends GroupPagingRow>(
  rows: readonly T[],
  page: number,
  pageSize: number,
): GroupPagingResult<T> {
  if (pageSize <= 0) throw new Error('pageSize must be positive');

  // Поставки в порядке первого появления; строки каждой — подряд.
  const order: string[] = [];
  const byGroup = new Map<string, T[]>();
  for (const row of rows) {
    const existing = byGroup.get(row.groupId);
    if (existing) {
      existing.push(row);
      continue;
    }
    byGroup.set(row.groupId, [row]);
    order.push(row.groupId);
  }

  // Набираем страницу поставками целиком: очередная поставка либо помещается,
  // либо целиком уезжает на следующую страницу. Поэтому строк выходит около
  // pageSize, а не ровно столько — зато поставка не рвётся никогда.
  //
  // Считаем именно так, а не «по числу строк перед поставкой»: поставка,
  // которая сама больше страницы, при таком делении оставляла бы после себя
  // пустую страницу в пагинаторе.
  const pages: T[][] = [];
  let current: T[] = [];
  for (const groupId of order) {
    const group = byGroup.get(groupId)!;
    if (current.length > 0 && current.length + group.length > pageSize) {
      pages.push(current);
      current = [];
    }
    current.push(...group);
    if (current.length >= pageSize) {
      pages.push(current);
      current = [];
    }
  }
  if (current.length > 0) pages.push(current);

  return {
    rows: pages[page - 1] ?? [],
    // Пустой набор — всё равно одна (пустая) страница: пагинатор не должен
    // показывать «0 страниц».
    pageCount: Math.max(1, pages.length),
  };
}
