/**
 * Страница списка документов, которая не разрывает поставку.
 *
 * Одна загрузка — это машина: пять УПД, приехавшие вместе, менеджер читает как
 * одну поставку. Пока страница резалась по документам, такая пятёрка могла
 * разъехаться между страницами: на первой три документа, на второй два, и
 * связь между ними терялась. Клиентская кластеризация тут бессильна — она
 * видит только загруженные строки.
 *
 * Поэтому окно страницы считается по ПОСТАВКАМ: строки уже отсортированы
 * сервером, поставка встаёт на место своего первого ДОКУМЕНТА, и целая
 * поставка попадает на ту страницу, где она началась. Из-за этого на странице
 * выходит не ровно `pageSize` строк, а «около»: у самой большой боевой
 * поставки одиннадцать документов, так что разброс невелик.
 *
 * Почему первый документ = правильное место поставки. Документы приходят уже
 * упорядоченными (по сумме, дате, статусу — как выбрал пользователь), значит
 * первым из своей поставки встретится ровно крайний: самый большой при
 * убывании, самый малый при возрастании.
 *
 * Почему именно документ, а не любая строка. Принятые файлы идут во входе
 * ПЕРЕД документами (свежая неразобранная машина должна быть видна сверху).
 * Пока место поставки задавала первая строка, файл, застрявший навсегда
 * (браузер поставщика не дослал его в хранилище), тянул на самый верх всю
 * старую поставку — с документами и принятой приёмкой — и свежие уезжали
 * вниз. Теперь файл встаёт внутрь своей поставки, а наверху остаётся только
 * поставка, у которой документов ещё нет.
 */

/** Строка выдачи: документ или принятый файл, до которого разбор не дошёл. */
export type GroupPagingRow = {
  id: string;
  /** Поставка: корневой пакет. У документа без пакета — он сам. */
  groupId: string;
  kind: 'doc' | 'pending';
};

export type GroupPagingResult<T> = {
  /** Строки запрошенной страницы, в исходном порядке. */
  rows: T[];
  /** Сколько всего страниц получилось при такой упаковке. */
  pageCount: number;
  /**
   * Сколько строк легло на предыдущие страницы. Страницы плавающие, поэтому
   * `(page - 1) * pageSize` тут не годится: если на первой странице 48 строк,
   * номера второй начинались бы с 51 и «№» 49–50 пропадали бы.
   */
  rowOffset: number;
};

/**
 * Режет упорядоченные строки на страницы, не разрывая поставку.
 *
 * `page` — с единицы, как в адресе. Страница за пределами набора даёт пустой
 * список: так же ведёт себя обычный offset.
 */
export function pageOfGroupedRows<T extends GroupPagingRow>(
  rows: readonly T[],
  page: number,
  pageSize: number,
): GroupPagingResult<T> {
  if (pageSize <= 0) throw new Error('pageSize must be positive');

  // Строки каждой поставки — подряд, в исходном порядке. Место поставки —
  // позиция её первого документа; поставка из одних принятых файлов стоит на
  // месте своей первой строки (см. шапку файла).
  const byGroup = new Map<string, T[]>();
  const anchor = new Map<string, number>();
  const hasDoc = new Set<string>();
  rows.forEach((row, index) => {
    const existing = byGroup.get(row.groupId);
    if (existing) existing.push(row);
    else byGroup.set(row.groupId, [row]);
    if (!anchor.has(row.groupId)) anchor.set(row.groupId, index);
    if (row.kind === 'doc' && !hasDoc.has(row.groupId)) {
      hasDoc.add(row.groupId);
      anchor.set(row.groupId, index);
    }
  });
  // Якоря различны (у каждой поставки — индекс своей строки), поэтому порядок
  // однозначен и не зависит от устойчивости sort.
  const order = [...byGroup.keys()].sort((a, b) => anchor.get(a)! - anchor.get(b)!);

  // Набираем страницу поставками целиком: очередная поставка либо помещается,
  // либо целиком уезжает на следующую страницу. Поэтому строк выходит около
  // pageSize, а не ровно столько — зато поставка не рвётся никогда.
  //
  // Считаем именно так, а не «по числу строк перед поставкой»: поставка,
  // которая сама больше страницы, при таком делении оставляла бы после себя
  // пустую страницу в пагинаторе.
  const pages: T[][] = [];
  let current: T[] = [];
  for (const groupId of order) {
    const group = byGroup.get(groupId)!;
    if (current.length > 0 && current.length + group.length > pageSize) {
      pages.push(current);
      current = [];
    }
    current.push(...group);
    if (current.length >= pageSize) {
      pages.push(current);
      current = [];
    }
  }
  if (current.length > 0) pages.push(current);

  return {
    rows: pages[page - 1] ?? [],
    // Пустой набор — всё равно одна (пустая) страница: пагинатор не должен
    // показывать «0 страниц».
    pageCount: Math.max(1, pages.length),
    rowOffset: pages.slice(0, Math.max(0, page - 1)).reduce((n, p) => n + p.length, 0),
  };
}
