/**
 * Сравнение названий организаций «по смыслу».
 *
 * Одно и то же юрлицо приходит из документов в разном написании: `ООО "СУ-10"`
 * из текстового слоя, `ООО «СУ-10»` из vision-ответа, с двойными пробелами
 * после переноса строки. Для человека это одна организация, для `===` — три
 * разные строки.
 *
 * Живёт в domain, потому что нужен и боевому коду (сравнение сторон документа
 * в party-directory-guard), и офлайн-сверке версий промпта
 * (scripts/prompt-ab-lib). Две реализации одного правила разъехались бы, и
 * тогда гейт сверки перестал бы соответствовать тому, что делает воркер.
 */

/** Нормализованное имя для сравнения: без кавычек, регистра и лишних пробелов. */
export function normalizeOrgName(v: string | null | undefined): string {
  if (!v) return '';
  return v
    .replace(/[«»"'']/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}
