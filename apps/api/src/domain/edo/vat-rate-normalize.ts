import type { UpdPdfParsed } from '@matcheck/contracts';

/**
 * Построчный НДС, противоречащий шапке документа, — почти всегда выдуманная
 * моделью ставка.
 *
 * Откуда берётся. Через УПД-поток идут не только УПД формы 1137: счета,
 * товарные чеки и заказы клиента попадают туда же (router отправляет в него
 * всё, кроме накладных). В таких бланках построчного НДС НЕТ вовсе — есть
 * только итог и «в том числе НДС». Модель это поле всё равно заполняет: берёт
 * привычную ставку 20 % и считает налог от суммы строки сама. Ставка и сумма
 * получаются согласованными ДРУГ С ДРУГОМ, поэтому ни одна построчная проверка
 * подвоха не видит.
 *
 * Чем это плохо. С 2026 года основная ставка 22 %, и синтез по 20 % занижает
 * налог: на боевом счёте № 223379 шапка прочитана верно (итог 57 809,97, НДС
 * 10 424,75 — ровно 22 % от базы), а сумма построчных vatSum дала 9 634,99 —
 * расхождение 790 ₽ внутри одного документа. За 30 дней таких документов
 * восемь, суммарный разрыв 7 653 ₽.
 *
 * Почему верна ИМЕННО шапка. Итог и сумма налога напечатаны крупно, часто
 * продублированы прописью, и читаются надёжнее мелкой табличной графы. А в
 * бланках без построчного НДС альтернативы шапке просто нет: единственное
 * место, где налог вообще напечатан.
 *
 * Осторожность правила. Оно срабатывает, только когда сомнений не остаётся:
 * ставка у ВСЕХ строк одна (документ со смешанными ставками не трогаем — их
 * 2 из 1232), она расходится с шапкой, и сумма построчного налога с шапкой не
 * сходится. Любое из условий не выполнено — возвращаем документ как есть.
 */

/**
 * Ставки, к которым разрешено приводить эффективную ставку шапки.
 *
 * Льготных 5 % и 7 % (УСН) здесь намеренно НЕТ. Не потому, что их не бывает, а
 * потому, что шапка с испорченной суммой налога даёт как раз маленькую ставку:
 * на боевых документах встретились 5,53 % и 6,59 % — оба раза шапка прочитана
 * неверно, а построчные 22 % были верны. Приняв такую шапку за льготную, мы
 * переписали бы правильные строки заведомо неправильными.
 */
const KNOWN_RATES = [0, 10, 20, 22] as const;

/**
 * Допуск при сверке ставки, в процентных пунктах.
 *
 * Тот же, что у детектора `suspectPriceIncludesVat`: эффективная ставка,
 * посчитанная от округлённых до копеек сумм, всегда немного «плавает».
 */
const RATE_TOLERANCE = 0.6;

/** Допуск при сверке сумм налога: копейка на строку, но не меньше рубля. */
function moneyTolerance(value: number, rows: number): number {
  return Math.max(1, Math.abs(value) * 0.005, rows * 0.01);
}

function round2(n: number): number {
  return Math.round((n + Number.EPSILON) * 100) / 100;
}

/**
 * Ставка документа по шапке, приведённая к напечатанной.
 *
 * Возвращает null, когда шапки не хватает или полученное значение не похоже ни
 * на одну реальную ставку: выдумывать ставку по мотивам испорченной шапки
 * опаснее, чем оставить строку как есть.
 */
export function headerVatRate(
  totalSum: number | null | undefined,
  vatSum: number | null | undefined,
): number | null {
  if (totalSum == null || vatSum == null) return null;
  if (!Number.isFinite(totalSum) || !Number.isFinite(vatSum)) return null;
  if (vatSum <= 0) return null;
  const base = totalSum - vatSum;
  if (base <= 0) return null;
  const rate = (vatSum / base) * 100;
  const nearest = KNOWN_RATES.reduce((best, r) =>
    Math.abs(r - rate) < Math.abs(best - rate) ? r : best,
  );
  return Math.abs(nearest - rate) <= RATE_TOLERANCE ? nearest : null;
}

/**
 * Привести построчный НДС к ставке документа, если он ей противоречит.
 *
 * Immutable: вход не мутируется, при срабатывании возвращается копия с
 * пересчитанными `vatRate`/`vatSum` у позиций. Во всех прочих случаях —
 * исходный объект без изменений.
 */
export function normalizeLineVatAgainstHeader(parsed: UpdPdfParsed): UpdPdfParsed {
  const items = parsed.items ?? [];
  if (items.length === 0) return parsed;

  const docRate = headerVatRate(parsed.totalSum ?? null, parsed.vatSum ?? null);
  if (docRate == null || docRate <= 0) return parsed;

  // Ставка должна быть известна у ВСЕХ строк и быть одной и той же. Пустая
  // ставка хотя бы у одной строки означает, что мы не знаем состава документа:
  // возможно, там «Без НДС», и приводить такую строку к ставке шапки нельзя.
  const rates = items.map((i) => i.vatRate ?? null);
  if (rates.some((r) => r == null || !Number.isFinite(r))) return parsed;
  const lineRate = rates[0] as number;
  if (rates.some((r) => r !== lineRate)) return parsed;

  // Ставка строк совпадает с шапкой — расхождения нет, трогать нечего.
  if (Math.abs(lineRate - docRate) <= RATE_TOLERANCE) return parsed;

  // Направление расхождения имеет значение: чиним ТОЛЬКО занижение.
  //
  // Лечится один конкретный случай — модель подставила устаревшую ставку (20 %
  // вместо действующих с 2026 года 22 %). Обратное направление, когда шапка
  // ниже построчной, означает либо льготный товар, либо испорченную сумму
  // налога в шапке. На боевых данных это ровно так и выглядело: у четырёх
  // документов шапка давала 5,5 / 6,6 / 9,6 / 20,5 %, а строки были верны.
  // Переписать их означало бы испортить правильные данные.
  if (docRate <= lineRate) return parsed;

  // Суммы строк обязаны сходиться с итогом документа.
  //
  // Это проверка на то, что документ вообще разобран связно. Если Σ строк не
  // равна итогу, то неизвестно, чему верить, — и шапке в том числе; такой
  // документ надо разбирать человеку, а не выравнивать эвристикой. На боевых
  // данных условие отсеивает 13 документов из 33 кандидатов.
  const total = parsed.totalSum ?? null;
  if (total == null || !Number.isFinite(total)) return parsed;
  const lineSumTotal = items.reduce((acc, i) => acc + (i.sum ?? 0), 0);
  if (Math.abs(lineSumTotal - total) > moneyTolerance(total, items.length)) return parsed;

  // Наконец, построчный налог не сходится с шапочным. Без этого условия правило
  // сработало бы на документе, где ставка записана иначе, но суммы верны.
  const headerVat = parsed.vatSum ?? null;
  if (headerVat == null) return parsed;
  const lineVatTotal = items.reduce((acc, i) => acc + (i.vatSum ?? 0), 0);
  if (Math.abs(lineVatTotal - headerVat) <= moneyTolerance(headerVat, items.length)) {
    return parsed;
  }

  return {
    ...parsed,
    items: items.map((i) => {
      // Сумма строки хранится С НАЛОГОМ (графа 9), поэтому налог из неё
      // выделяется, а не начисляется сверху.
      const sum = i.sum ?? null;
      const vatSum =
        sum != null && Number.isFinite(sum) ? round2(sum - sum / (1 + docRate / 100)) : i.vatSum;
      return { ...i, vatRate: docRate, vatSum };
    }),
  };
}
