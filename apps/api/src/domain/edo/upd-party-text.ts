/**
 * Разбор строк-сторон УПД: выделение значения графы и отделение адреса от
 * наименования.
 *
 * `matchParty` вынесена из upd-xlsx.parser.ts БЕЗ изменений: XLSX-путь ею
 * пользуется давно и regression-тестами закрыт, а PDF-путь имел собственную
 * регулярку графы 4, которая на формате с двоеточием захватывала сам ярлык
 * («Грузополучатель и его адрес:» → в поле попадало «и его адрес:»). Общий
 * модуль вместо второй реализации — чтобы обе формы разбирались одним и тем
 * же кодом и расхождение больше не могло возникнуть.
 *
 * `nameBeforeAddress` собрана здесь по той же причине: своё деление по первой
 * запятой было у PDF-парсера и у XLSX-парсера, а vision-путь не резал адрес
 * вовсе — и в колонку попадало «ООО "СУ-10", 127018, Город Москва, …».
 */

/**
 * Достаёт значение стороны из строки вида «<подпись> <значение> <терминатор>».
 *
 * @param line          строка документа
 * @param prefixRe      подпись графы; двоеточие описывается как `:?`
 * @param terminatorAlt альтернация того, чем значение заканчивается —
 *                      номер графы, следующая подпись, «ИНН», «Валюта:»
 * @returns значение без хвостового тега графы, либо null — если подпись не
 *          найдена или после неё пусто. Возврат null вместо подписи —
 *          principial: пустая графа не должна выглядеть заполненной.
 */
export function matchParty(
  line: string,
  prefixRe: RegExp,
  terminatorAlt: RegExp,
): string | null {
  const startMatch = prefixRe.exec(line);
  if (!startMatch) return null;
  const tail = line.slice(startMatch.index + startMatch[0].length);
  const endMatch = terminatorAlt.exec(tail);
  const raw = (endMatch ? tail.slice(0, endMatch.index) : tail).trim();
  if (!raw) return null;
  return raw.replace(/\s*\(\d+[а-я]?\)\s*$/u, '').trim() || null;
}

/** Пары кавычек, внутри которых запятая — часть названия, а не разделитель. */
const QUOTE_PAIRS: Record<string, string> = { '«': '»', '"': '"', '“': '”', "'": "'" };

/**
 * Отрезает адрес от наименования в графах вида «наименование и его адрес».
 *
 * Форма 1137 печатает грузоотправителя и грузополучателя одной строкой:
 * «ООО "СУ-10", Россия, 117335, Город Москва, ул. Вавилова, дом 69/75, …».
 * Название юрлица идёт первым и заканчивается на первой запятой — дальше
 * всегда адрес.
 *
 * Запятые ВНУТРИ кавычек границей не считаются: `ООО "Альфа, Бета", 127018,
 * Москва` — это организация «Альфа, Бета», а не «Альфа». Наивное
 * `split(',')[0]`, которое было в обоих текстовых парсерах, на таком названии
 * отрезало бы половину имени.
 *
 * Строка без запятых возвращается как есть — это обычный случай, когда адрес
 * в графе не напечатан.
 */
export function nameBeforeAddress(s: string | null | undefined): string | null {
  if (!s) return null;

  let closing: string | null = null;
  let cut = -1;
  for (let i = 0; i < s.length; i++) {
    const ch = s[i]!;
    if (closing) {
      // Внутри кавычек ищем только закрывающую: всё остальное — часть названия.
      if (ch === closing) closing = null;
      continue;
    }
    const opening = QUOTE_PAIRS[ch];
    if (opening) {
      closing = opening;
      continue;
    }
    if (ch === ',') {
      cut = i;
      break;
    }
  }

  const head = cut === -1 ? s : s.slice(0, cut);
  const trimmed = head.trim();
  return trimmed.length ? trimmed : null;
}
