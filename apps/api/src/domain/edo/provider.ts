/**
 * Оператор учётки ЭДО.
 *
 * Пути Диадока — опрос, выгрузка реестра, осмотр ящика, проверка доступа,
 * пробный разбор — работают только с учётками Диадока. Учётка другого
 * оператора (СБИС), попав туда, получила бы клиент Диадока со своими ключами,
 * записала бы курсор и журнал от чужого запроса ленты и каждые полчаса слала
 * бы ошибку. Поэтому каждый такой путь отсекает её ДО лиза, курсора, журнала и
 * клиента.
 */
export const DIADOC_PROVIDER = 'diadoc';

export function isDiadocAccount(account: { provider: string }): boolean {
  return account.provider === DIADOC_PROVIDER;
}

/** Ответ админки на действие Диадока для учётки другого оператора. */
export const PROVIDER_NOT_SUPPORTED = {
  error: 'provider_not_supported',
  status: 409 as const,
  message: 'Действие доступно только для учётки Диадока.',
};
