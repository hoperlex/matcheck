/**
 * Опознание товарно-транспортной накладной формы № 1-Т по тексту файла.
 *
 * Зачем. Активный промпт накладных знает две формы — ТН-2116 и ОС-2 — и по
 * собственной инструкции обязан 1-Т игнорировать: её разбирает отдельный
 * промпт. Но модель инструкцию нарушает и читает 1-Т по колонкам формы 2116, а
 * там на месте количества стоит графа «Кол-во мест». На боевых ТТН это дало
 * `qty=14` вместо 1260 шт, цену 1 260 000 ₽ (туда попало количество) и итог
 * документа, взятый из графы «Количество». Проверить форму ДО обращения к
 * модели можно без единого вызова: у печатных ТТН есть текстовый слой.
 *
 * Признак намеренно узкий: заголовок формы вместе с одним из её опознавательных
 * знаков. Ложное срабатывание здесь дороже пропуска — оно увело бы к чужому
 * промпту накладную, которая сегодня разбирается верно.
 *
 * Фотографии и сканы без текстового слоя детектор не опознаёт вовсе — там
 * форму называет сама модель (см. второй триггер в worker).
 */
import { PDFParse } from 'pdf-parse';

/** Заголовок формы. Без него дальше не смотрим. */
const TITLE_RE = /товарно\s*-?\s*транспортн[а-яё]*\s+накладн[а-яё]*/i;

/**
 * Опознавательные знаки бланка: код формы по ОКУД, номер типовой формы,
 * постановление Госкомстата и пара разделов, которых нет у ТН-2116.
 */
const FORM_MARKERS: RegExp[] = [
  /0345009/,
  /типов[а-яё]*\s+(?:межотраслев[а-яё]*\s+)?форм[а-яё]*\s+№?\s*1\s*-?\s*т/i,
  /госкомстат[а-яё]*\s+росси[а-яё]*\s+от\s+28\.11\.97/i,
  /товарн[а-яё]*\s+раздел[а-яё]*\s*\(заполняется\s+грузоотправителем\)/i,
];

/** Текст, по которому выносится вердикт. Экспортирован ради тестов. */
export function isWaybill1tText(text: string): boolean {
  if (!text) return false;
  const flat = text.replace(/\s+/g, ' ');
  if (!TITLE_RE.test(flat)) return false;
  return FORM_MARKERS.some((re) => re.test(flat));
}

/**
 * Форма 1-Т ли это. Читает текстовый слой PDF; для остальных типов и для
 * сканов без текста возвращает false — маршрут файла не меняется.
 *
 * Ошибки чтения PDF проглатываются: битый текстовый слой это не повод менять
 * маршрут, файл пойдёт прежним путём.
 */
export async function detectWaybill1t(buffer: Buffer, mimeType: string): Promise<boolean> {
  if (!/pdf/i.test(mimeType)) return false;
  try {
    const parser = new PDFParse({ data: new Uint8Array(buffer) });
    try {
      const r = await parser.getText();
      return isWaybill1tText(r.text ?? '');
    } finally {
      await parser.destroy().catch(() => undefined);
    }
  } catch {
    return false;
  }
}
