// Текст письма для распознавания и для показа оператору.
//
// Зачем отдельный модуль. mailparser сам переводит html в текст далеко не
// всегда: условие в его mail-parser.js — `(!alternative && hasText) ||
// (node.root && !hasText)`. То есть текст появляется, только если письмо это
// голый `text/html` в корне либо рядом лежит настоящая текстовая часть. Для
// html-письма внутри `multipart/alternative`, `related` или `mixed` — а это
// обычная форма писем из Outlook и mail.ru — `parsed.text` остаётся пустым.
//
// Цена такой пустоты не «не видно текста», а хуже: матчер объекта, парсер даты
// поставки и парсер направления работают по этому же полю, поэтому у html-
// письма тело для них просто не существует, и решение принимается по одной
// теме. Отсюда правило: текст письма берётся ТОЛЬКО через эту функцию.

import { convert } from 'html-to-text';
import type { ParsedMail } from 'mailparser';

/**
 * Текстовое представление письма: текстовая часть, а при её отсутствии — html,
 * переведённый в текст. Возвращает пустую строку, если в письме нет ни того,
 * ни другого.
 *
 * Разметка наружу не отдаётся ни в каком виде — только результат конвертации.
 */
export function extractPlainText(parsed: ParsedMail): string {
  const text = parsed.text?.trim();
  if (text) return text;
  // parsed.html === false, когда html-части нет вовсе (так его помечает
  // mailparser), поэтому проверяем именно тип.
  if (typeof parsed.html !== 'string' || !parsed.html) return '';
  try {
    // wordwrap выключен: переносы по 80 колонок разорвали бы названия объектов
    // («Сити Бей 2») и сломали бы сопоставление написаний.
    return convert(parsed.html, { wordwrap: false }).trim();
  } catch {
    // Битую разметку молча пропускаем: письмо важнее его оформления, а тема и
    // вложения уже разобраны.
    return '';
  }
}
