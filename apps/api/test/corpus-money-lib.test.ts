/**
 * Тесты на разбор текстового слоя УПД для черновой денежной разметки.
 *
 * Этот разбор готовит ЭТАЛОН, по которому решается, включать ли новую версию
 * промпта. Ошибка здесь не портит отчёт, а запрещает верную версию или
 * пропускает неверную — то есть стоит дороже обычного бага.
 *
 * Строки ниже — НАСТОЯЩИЕ, из корпуса (`docs/debug-upd`), а не сочинённые:
 * разбор опирается на координаты колонок, и синтетическая строка проверяла бы
 * не тот формат, что приходит на вход. Каждый случай — то, на чём разбор молча
 * ошибся при первом прогоне; ловила их только сверка суммы позиций с итогом.
 */
import { describe, it, expect } from 'vitest';
import { extract } from '../scripts/corpus-money-lib.js';

// УПД № 258 — обычный бланк: запятая в дробной части, отдельная строка-услуга.
const INVOICE = 'Универсальный        Счет-фактура №                      258               от           2 июля 2026 г.           (1)                                                 Приложение № 1 к постановлению Правительства Российской Федерации от 26 декабря 2011 г. № 1137';
const HEADER = '       А              1                     1а                        1б     2      2а              3             4                    5              6          7                 8                  9            10             10а                 11';
const ROW_1 = '00-00002725                1 Грунт антикоррозийный цинковый --             796 шт                  100,000             335,08          33 508,20       без 22%                     7 371,80           40 880,00 --        --                --';
const ROW_SERVICE = '00-00000102                 4 Доставка                            --           --   --                         --                    --              1 639,34        без 22%                           360,66                  2 000,00 --        --                  --';
const TOTAL = '                    Всего к оплате (9)                                                                                                          184 606,55                    Х                   40 613,45                225 220,00';

// зиларт.pdf — другой бланк: «СЧЕТ-ФАКТУРА» заглавными, точка вместо запятой.
const Z_INVOICE = '                             СЧЕТ-ФАКТУРА       № 201/21126372 от';
const Z_HEADER = '             А           1                 1а                           1б       2          2а            3           4              5               6           7              8              9            10         10а                            11';
const Z_ROW = ' 91920                    1 Труба гофрированная ПВХ 20 мм с про --             006 м                          400         12.26     4904.92 без акциза               22%       1079.08         5984.00      -         ---                              ---';
const Z_TOTAL = '                             Всего к оплате                                                                                         4904.92                 X                  1079.08         5984.00';

// 201_2112636922…PRINTER2.TXT.pdf — бланк, на котором срез колонки склеивал
// соседние ячейки: количество 22 превращалось в 221, цена 40.27 — в 540.27.
const M_INVOICE_A = '                             СЧЕТ-ФАКТУРА       № 201/2112636922 от';
const M_HEADER_A = '             А           1                 1а                            1б      2          2а            3           4              5               6           7              8              9            10         10а                            11';
const M_ROW_A = ' HR 12-34 W               1 Аккумулятор HR 12В 9Ач                  --         796 шт                         22     1505.66       33124.43 без акциза               22%       7287.37        40411.80 704        Вьетнам       10702070/061025/5349726';
const M_TOTAL_A = '                             Всего к оплате                                                                                        33124.43                 X                  7287.37        40411.80';
const M_INVOICE_B = '                          СЧЕТ-ФАКТУРА     № 201/21126387-1 от';
const M_HEADER_B = '           А           1                 1а                           1б       2          2а           3           4              5              6            7              8              9            10         10а                            11';
const M_ROW_B = 'С4935                   2 Витая пара СегментЛАН U/UTP Cat5e Z --             006 м                         305         40.27    12282.35 без акциза               22%       2702.12        14984.47      -         ---                              ---';

describe('extract — разбор таблицы УПД из текстового слоя', () => {
  it('берёт количество, цену, НДС и стоимость с налогом из своих граф', () => {
    const [doc] = extract([INVOICE, HEADER, ROW_1, TOTAL].join('\n'));
    expect(doc?.docNumber).toBe('258');
    // qty — графа 3, price — графа 4 (без НДС), vatSum — графа 8,
    // sum — графа 9 (с НДС). Именно эти графы просит промпт.
    expect(doc?.items[0]).toEqual({
      rowNo: 1,
      qty: 100,
      price: 335.08,
      sum: 40880,
      vatSum: 7371.8,
    });
  });

  it('срез колонки не приклеивает цифру соседней графы к количеству', () => {
    // Настоящий бланк: "…796 шт                         22     1505.66…".
    // Правая граница среза графы 3 обрывалась на «1» от цены, а пробелы внутри
    // числа считались разделителем тысяч — получалось 221. Ошибка не видна ни
    // по сумме строки, ни по итогу документа: они остаются верными.
    const [doc] = extract([M_INVOICE_A, M_HEADER_A, M_ROW_A, M_TOTAL_A].join('\n'));
    expect(doc?.items[0]).toMatchObject({ rowNo: 1, qty: 22, price: 1505.66, sum: 40411.8 });
    expect(doc?.items[0]?.mismatch).toBeUndefined();
  });

  it('срез колонки не приклеивает хвост количества к цене', () => {
    // Тот же файл, другой субдокумент: "…006 м                         305         40.27…".
    // Левая граница среза графы 4 расширена на шесть символов (числа заходят
    // левее метки) и захватывала «5» от количества 305 — цена становилась 540.27.
    const [doc] = extract([M_INVOICE_B, M_HEADER_B, M_ROW_B].join('\n'));
    expect(doc?.items[0]).toMatchObject({ rowNo: 2, qty: 305, price: 40.27, sum: 14984.47 });
    expect(doc?.items[0]?.mismatch).toBeUndefined();
  });

  it('строка, где количество × цена не сходится со стоимостью, помечается', () => {
    // Страховка на будущее: если срез снова начнёт врать (другой бланк, другая
    // вёрстка), строка не должна молча уехать в эталон. Подделываем цену прямо
    // в исходной строке — сумма и НДС при этом остаются прежними, как и бывает
    // при ошибке нарезки.
    const broken = M_ROW_A.replace('1505.66', '1605.66');
    const [doc] = extract([M_INVOICE_A, M_HEADER_A, broken, M_TOTAL_A].join('\n'));
    expect(doc?.items[0]?.mismatch).toMatch(/против стоимости без налога/);
  });

  it('строка-услуга с прочерками в количестве и цене не теряется', () => {
    // «Доставка» печатается без количества и цены — и это самый ценный случай
    // для эталона: он утверждает, что цены в бланке НЕТ, и ловит модель, когда
    // та её выдумывает. Первый прогон требовал непустое количество и молча
    // выбрасывал такие строки, после чего итог переставал сходиться.
    const [doc] = extract([INVOICE, HEADER, ROW_SERVICE].join('\n'));
    expect(doc?.items[0]).toMatchObject({ rowNo: 4, qty: null, price: null });
    expect(doc?.items[0]?.sum).not.toBeNull();
  });

  it('копейки через точку не теряются', () => {
    // Часть бланков печатает «5984.00» вместо «5984,00». Разбор только с
    // запятой округлял суммы, и документ расходился с итогом на рубль.
    const [doc] = extract([Z_INVOICE, Z_HEADER, Z_ROW, Z_TOTAL].join('\n'));
    expect(doc?.items[0]?.price).toBe(12.26);
    expect(doc?.items[0]?.sum).toBe(5984);
  });

  it('«СЧЕТ-ФАКТУРА» заглавными тоже начинает документ', () => {
    // Из-за регистрозависимого поиска целые файлы не давали ни одной позиции.
    const [doc] = extract([Z_INVOICE, Z_HEADER, Z_ROW].join('\n'));
    expect(doc?.docNumber).toBe('201/21126372');
  });

  it('второй экземпляр той же бумаги не удваивает позиции', () => {
    // В пачке документ печатают дважды. Первый прогон дописывал позиции копии
    // к оригиналу: 11 968 против итога 5 984 — ровно вдвое.
    const one = [Z_INVOICE, Z_HEADER, Z_ROW, Z_TOTAL].join('\n');
    const docs = extract([one, one].join('\n'));
    expect(docs).toHaveLength(1);
    expect(docs[0]?.items).toHaveLength(1);
    expect(docs[0]?.totalsMismatch).toBeUndefined();
  });

  it('реквизиты со следующей страницы не попадают в позиции', () => {
    // После «Всего к оплате» таблица кончилась: ниже шапка следующего листа, где
    // в координатах графы 1 стоит ИНН продавца. Он приезжал позицией 7716794678.
    const text = [
      INVOICE,
      HEADER,
      ROW_1,
      TOTAL,
      '                      ИНН/КПП продавца:                         7716794678/504301001',
    ].join('\n');
    const [doc] = extract(text);
    expect(doc?.items.map((i) => i.rowNo)).toEqual([1]);
  });

  it('расхождение итога с суммой позиций помечается, а не замалчивается', () => {
    // Единственная проверка, которая ловит ПОТЕРЯННУЮ строку: черновик без неё
    // выглядит полным, просто в нём на одну позицию меньше.
    const [doc] = extract([INVOICE, HEADER, ROW_1, ROW_SERVICE, TOTAL].join('\n'));
    expect(doc?.totalsMismatch).toContain('против итога');
  });
});

describe('extract — непокрытые документы помечаются явно', () => {
  it('без «Всего к оплате» документ помечается непокрытым', () => {
    // Такой документ выглядит в черновике так же аккуратно, как проверенный:
    // позиции есть, числа на месте. Но сверить их полноту не с чем — потерянную
    // строку заметить нечем. Пометка нужна, чтобы его не перенесли в эталон.
    const [doc] = extract([INVOICE, HEADER, ROW_1].join('\n'));
    expect(doc?.notCovered).toContain('итог');
    expect(doc?.items).toHaveLength(1);
  });

  it('с итогом пометки нет', () => {
    const [doc] = extract([INVOICE, HEADER, ROW_1, TOTAL].join('\n'));
    expect(doc?.notCovered).toBeUndefined();
  });
});
