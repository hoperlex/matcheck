/**
 * Разбор XML УПД: актуальный формат ФНС, прежний формат и оценка полноты.
 *
 * ВАЖНО про фикстуры. Они собраны по описанию формата, а НЕ выгружены из
 * боевого ящика: реальных документов у нас пока нет. Поэтому тест доказывает
 * ровно две вещи — что парсер понимает вложенность и имена полей формата, и что
 * неполный разбор он называет неполным. Подтверждение на настоящих документах
 * (820, 970/5.02, 970/5.03) остаётся обязательным шагом перед импортом.
 *
 * Прежний формат проверяется рядом намеренно: маршрут ручной загрузки XML
 * живой, и менять его поведение этой правкой нельзя.
 */
import { describe, it, expect } from 'vitest';
import { parseUpdXml, assessUpdParse } from '../src/domain/edo/upd.parser.js';
import { decodeXmlBuffer, detectXmlEncoding } from '../src/domain/edo/upd-xml-decode.js';

/** УПД по формату: номер и дата в СвСчФакт, стороны через ИдСв → СвЮЛУч. */
const UTD_MODERN = `<?xml version="1.0" encoding="UTF-8"?>
<Файл ИдФайл="ON_NSCHFDOPPR_2BM">
  <Документ КНД="1115131" Функция="СЧФДОП" ДатаИнфПр="01.09.2026">
    <СвСчФакт НомерСчФ="УТ-4308" ДатаСчФ="01.09.2026">
      <СвПрод>
        <ИдСв>
          <СвЮЛУч НаимОрг="ООО «Металлбаза»" ИННЮЛ="7712345678" КПП="771201001"/>
        </ИдСв>
      </СвПрод>
      <СвПокуп>
        <ИдСв>
          <СвЮЛУч НаимОрг="ООО «СУ-10»" ИННЮЛ="7736030001" КПП="773601001"/>
        </ИдСв>
      </СвПокуп>
    </СвСчФакт>
    <ТаблСчФакт>
      <СведТов НомСтр="1" НаимТов="Труба стальная 57х3.5" ОКЕИ_Тов="168" НаимЕдИзм="т"
               КолТов="2.5" ЦенаТов="64000" СтТовБезНДС="160000" НалСт="20%" СтТовУчНал="192000">
        <СумНал><СумНал>32000</СумНал></СумНал>
      </СведТов>
      <СведТов НомСтр="2" НаимТов="Уголок 50х50" ОКЕИ_Тов="168" НаимЕдИзм="т"
               КолТов="1" ЦенаТов="58000" СтТовБезНДС="58000" НалСт="20%" СтТовУчНал="69600">
        <СумНал><СумНал>11600</СумНал></СумНал>
      </СведТов>
      <ВсегоОпл СтТовБезНДСВсего="218000" СтТовУчНалВсего="261600">
        <СумНалВсего><СумНал>43600</СумНал></СумНалВсего>
      </ВсегоОпл>
    </ТаблСчФакт>
  </Документ>
</Файл>`;

/** Тот же документ в прежних именах — как его читал парсер до правки. */
const UTD_LEGACY = `<?xml version="1.0" encoding="UTF-8"?>
<Файл ИдФайл="test">
  <Документ КНД="1115131" НомерДок="УТ-4308" ДатаДок="01.09.2026">
    <СвСчФакт>
      <СвПрод ИННЮЛ="7712345678" КПП="771201001" НаимОрг="ООО «Металлбаза»"/>
      <СвПокуп ИННЮЛ="7736030001" КПП="773601001" НаимОрг="ООО «СУ-10»"/>
      <ТаблСчФакт>
        <СведТов НомСтр="1" НаимТов="Труба стальная" КолТов="2" ОКЕИ_Тов="шт"
                 ЦенаТов="100" СтоимТовБезНДС="200" НалСт="20" СтоимНалог="40"/>
        <ВсегоОпл СтоимТовБезНДСВсего="200" СумНалВсего="40"/>
      </ТаблСчФакт>
    </СвСчФакт>
  </Документ>
</Файл>`;

describe('актуальный формат ФНС', () => {
  const parsed = parseUpdXml(UTD_MODERN);

  it('номер и дата берутся из СвСчФакт, а не из корня документа', () => {
    expect(parsed.docNumber).toBe('УТ-4308');
    expect(parsed.docDate).toBe('2026-09-01');
  });

  it('стороны читаются через вложенность ИдСв → СвЮЛУч', () => {
    expect(parsed.supplier).toEqual({
      inn: '7712345678',
      kpp: '771201001',
      name: 'ООО «Металлбаза»',
    });
    expect(parsed.recipient?.inn).toBe('7736030001');
  });

  it('суммы строк читаются из СтТовБезНДС, налог — из вложенного СумНал', () => {
    expect(parsed.items).toHaveLength(2);
    expect(parsed.items[0]).toMatchObject({
      nameRaw: 'Труба стальная 57х3.5',
      qty: 2.5,
      price: 64000,
      sum: 160000,
      vatSum: 32000,
    });
  });

  it('ставка «20%» становится числом', () => {
    expect(parsed.items[0]?.vatRate).toBe(20);
  });

  it('в единице измерения наименование, а не код ОКЕИ', () => {
    // «168» в карточке — это код, который менеджер прочитать не может.
    expect(parsed.items[0]?.unit).toBe('т');
  });

  it('итоги читаются вместе с вложенным СумНалВсего', () => {
    expect(parsed.totalSum).toBe(218000);
    expect(parsed.vatSum).toBe(43600);
  });
});

describe('прежний формат остаётся читаемым', () => {
  it('ручная загрузка XML работает как раньше', () => {
    const parsed = parseUpdXml(UTD_LEGACY);
    expect(parsed.docNumber).toBe('УТ-4308');
    expect(parsed.docDate).toBe('2026-09-01');
    expect(parsed.supplier.inn).toBe('7712345678');
    expect(parsed.items[0]).toMatchObject({ qty: 2, sum: 200, vatSum: 40 });
    expect(parsed.totalSum).toBe(200);
  });
});

describe('кодировка', () => {
  it('windows-1251 распознаётся по декларации и читается верно', () => {
    const xml = UTD_MODERN.replace('encoding="UTF-8"', 'encoding="windows-1251"');
    const buffer = Buffer.from(
      Array.from(xml).map((ch) => {
        const code = ch.charCodeAt(0);
        // Кириллица в 1251 лежит подряд с 0xC0; кавычки-ёлочки — отдельные коды.
        if (code >= 0x410 && code <= 0x44f) return code - 0x410 + 0xc0;
        if (ch === '«') return 0xab;
        if (ch === '»') return 0xbb;
        return code;
      }),
    );
    expect(detectXmlEncoding(buffer)).toBe('windows-1251');
    const parsed = parseUpdXml(decodeXmlBuffer(buffer));
    expect(parsed.supplier.name).toBe('ООО «Металлбаза»');
    expect(parsed.items[0]?.nameRaw).toContain('Труба стальная');
  });

  it('файл без объявленной кодировки читается как UTF-8', () => {
    const buffer = Buffer.from('<Файл><Документ/></Файл>', 'utf-8');
    expect(detectXmlEncoding(buffer)).toBe('utf-8');
    expect(decodeXmlBuffer(buffer)).toContain('Файл');
  });
});

describe('оценка полноты разбора', () => {
  it('полный документ принимается', () => {
    expect(assessUpdParse(parseUpdXml(UTD_MODERN))).toEqual({ ok: true });
  });

  it('документ без номера не годится для карточки', () => {
    const xml = UTD_MODERN.replace('НомерСчФ="УТ-4308"', 'НомерСчФ=""');
    const verdict = assessUpdParse(parseUpdXml(xml));
    expect(verdict.ok).toBe(false);
    expect(verdict.ok === false && verdict.reasons).toContain('не прочитан номер документа');
  });

  it('позиции с пустыми количеством и суммой — признак чужих имён полей', () => {
    // Ровно это и происходило бы, читай парсер несуществующие атрибуты:
    // исключения нет, документ «разобран», а принимать по нему нечего.
    // Обнуляем ОБА поля суммы: у парсера есть запасное «с налогом», и пока оно
    // заполнено, строка остаётся осмысленной — это верное поведение.
    const xml = UTD_MODERN.replace(/КолТов="[\d.]+"/g, 'КолТов=""')
      .replace(/СтТовБезНДС="\d+"/g, 'СтТовБезНДС=""')
      .replace(/СтТовУчНал="\d+"/g, 'СтТовУчНал=""');
    const verdict = assessUpdParse(parseUpdXml(xml));
    expect(verdict.ok).toBe(false);
    expect(verdict.ok === false && verdict.reasons).toContain(
      'во всех позициях пусты и количество, и сумма',
    );
  });

  it('документ без позиций не годится', () => {
    const xml = UTD_MODERN.replace(/<СведТов[\s\S]*?<\/СведТов>/g, '');
    const verdict = assessUpdParse(parseUpdXml(xml));
    expect(verdict.ok === false && verdict.reasons).toContain('не прочитана ни одна позиция');
  });
});
