describe('формат 5.01', () => {
  // Та же форма, что UTD_MODERN, но с полями, которых там нет: исправление,
  // наименование единицы в ДопСведТов, валюта атрибутом СвСчФакт.
  const xml = UTD_MODERN.replace(
    'НомерСчФ="УТ-4308" ДатаСчФ="01.09.2026">',
    'НомерСчФ="УТ-4308" ДатаСчФ="01.09.2026" КодОКВ="643"><ИспрСчФ НомИспрСчФ="2" ДатаИспрСчФ="03.09.2026"/>',
  )
    .replace(' НаимЕдИзм="т"\n               КолТов="2.5"', '\n               КолТов="2.5"')
    .replace(
      '<СумНал><СумНал>32000</СумНал></СумНал>',
      '<СумНал><СумНал>32000</СумНал></СумНал><ДопСведТов ПрТовРаб="1" НаимЕдИзм="тонна"/>',
    );
  const parsed = parseUpdXml(xml);

  it('исправление, валюта и единица из ДопСведТов', () => {
    expect(parsed.correction).toEqual({ number: '2', date: '2026-09-03' });
    expect(parsed.currencyCode).toBe('643');
    expect(parsed.items[0]).toMatchObject({ unit: 'тонна', kind: 1 });
  });
});

describe('несколько продавцов и покупателей', () => {
  it('читаются все, первый остаётся основным', () => {
    const xml = UTD_MODERN.replace(
      '</СвПрод>',
      '</СвПрод><СвПрод><ИдСв><СвИП ИННФЛ="500100732259"><ФИО Фамилия="Железнов" Имя="Иван"/></СвИП></ИдСв></СвПрод>',
    );
    const parsed = parseUpdXml(xml);
    expect(parsed.supplier.inn).toBe('7712345678');
    expect(parsed.suppliers.map((s) => [s.inn, s.name])).toEqual([
      ['7712345678', 'ООО «Металлбаза»'],
      ['500100732259', 'Железнов Иван'],
    ]);
    expect(parsed.buyers).toHaveLength(1);
  });
});

describe('строение XML для диагностики', () => {
  it('пути объединены по строкам и без индексов', () => {
    const outline = xmlOutline(UTD_503);
    expect(outline).toContain('Файл/Документ/СвСчФакт/@НомерДок');
    expect(outline).toContain('Файл/Документ/ТаблСчФакт/СведТов/ДопСведТов/@ПрТовРаб');
    // Две позиции дают одну строку пути, а не две.
    expect(outline.filter((p) => p === 'Файл/Документ/ТаблСчФакт/СведТов/@НомСтр')).toHaveLength(1);
    expect(outline).toContain('Файл/Документ/ТаблСчФакт/СведТов/СумНал/СумНал');
  });

  it('предел соблюдается', () => {
    expect(xmlOutline(UTD_503, 5)).toHaveLength(5);
  });
});

describe('кодировка', () => {
  it('windows-1251 распознаётся по декларации и читается верно', () => {
    const xml = UTD_MODERN.replace('encoding="UTF-8"', 'encoding="windows-1251"');
    const buffer = Buffer.from(
      Array.from(xml).map((ch) => {
        const code = ch.charCodeAt(0);
        // Кириллица в 1251 лежит подряд с 0xC0; кавычки-ёлочки — отдельные коды.
        if (code >= 0x410 && code <= 0x44f) return code - 0x410 + 0xc0;
        if (ch === '«') return 0xab;
        if (ch === '»') return 0xbb;
        return code;
      }),
    );
    expect(detectXmlEncoding(buffer)).toBe('windows-1251');
    const parsed = parseUpdXml(decodeXmlBuffer(buffer));
    expect(parsed.supplier.name).toBe('ООО «Металлбаза»');
    expect(parsed.items[0]?.nameRaw).toContain('Труба стальная');
  });

  it('файл без объявленной кодировки читается как UTF-8', () => {
    const buffer = Buffer.from('<Файл><Документ/></Файл>', 'utf-8');
    expect(detectXmlEncoding(buffer)).toBe('utf-8');
    expect(decodeXmlBuffer(buffer)).toContain('Файл');
  });
});

describe('оценка полноты разбора', () => {
  it('полный документ принимается', () => {
    expect(assessUpdParse(parseUpdXml(UTD_MODERN))).toEqual({ ok: true });
  });

  it('документ без номера не годится для карточки', () => {
    const xml = UTD_MODERN.replace('НомерСчФ="УТ-4308"', 'НомерСчФ=""');
    const verdict = assessUpdParse(parseUpdXml(xml));
    expect(verdict.ok).toBe(false);
    expect(verdict.ok === false && verdict.reasons).toContain('не прочитан номер документа');
  });

  it('позиции с пустыми количеством и суммой — признак чужих имён полей', () => {
    // Ровно это и происходило бы, читай парсер несуществующие атрибуты:
    // исключения нет, документ «разобран», а принимать по нему нечего.
    // Обнуляем ОБА поля суммы: у парсера есть запасное «с налогом», и пока оно
    // заполнено, строка остаётся осмысленной — это верное поведение.
    const xml = UTD_MODERN.replace(/КолТов="[\d.]+"/g, 'КолТов=""')
      .replace(/СтТовБезНДС="\d+"/g, 'СтТовБезНДС=""')
      .replace(/СтТовУчНал="\d+"/g, 'СтТовУчНал=""');
    const verdict = assessUpdParse(parseUpdXml(xml));
    expect(verdict.ok).toBe(false);
    expect(verdict.ok === false && verdict.reasons).toContain(
      'во всех позициях пусты и количество, и сумма',
    );
  });

  it('документ без позиций не годится', () => {
    const xml = UTD_MODERN.replace(/<СведТов[\s\S]*?<\/СведТов>/g, '');
    const verdict = assessUpdParse(parseUpdXml(xml));
    expect(verdict.ok === false && verdict.reasons).toContain('не прочитана ни одна позиция');
  });
});
