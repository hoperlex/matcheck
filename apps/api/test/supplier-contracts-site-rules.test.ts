/**
 * Объект договора 1С по тексту. Строки — из настоящей выгрузки «Договоры с
 * контрагентами из группы Снабжение» (номер строки листа в комментарии).
 */
import { describe, expect, it } from 'vitest';
import { detectContractSites, siteRuleText } from '../src/domain/supplier-contracts/site-rules.js';

const detect = (name: string, number: string | null = null, object: string | null = null) =>
  detectContractSites(siteRuleText([name, number, object]));

describe('объект договора по тексту', () => {
  it('«0002-KING-Инж» — КИНГ, не ИНДЖ (стр. 6: «Инж» — направление, не объект)', () => {
    const r = detect('Распред.письмо № 0002-KING-Инж от 29.10.2026 г', '0002-KING-Инж');
    expect(r).toMatchObject({ status: 'exact', codes: ['КИНГ'] });
  });

  it('«0011-INJOY-Инж» — ИНДЖ', () => {
    expect(detect('Распред.письмо № 0011-INJOY-Инж от 02.07.2026 г', '0011-INJOY-Инж')).toMatchObject({
      status: 'exact',
      codes: ['ИНДЖ'],
    });
  });

  it('распред. письмо без объекта — none', () => {
    expect(detect('Распред.письмо № 2-30/09/26-РП от 30.09.2026 г', '2-30/09/26-РП')).toMatchObject({
      status: 'none',
      codes: [],
    });
  });

  it('стр. 1931: адрес 71/13, номер СУ-ПРИМ22 — спорный, оба претендента', () => {
    const r = detect('Волоколамское ш., вл.71/13 к.13, ДГ №СУ-ПРИМ22/2023-30 от 14.12.23', 'СУ-ПРИМ22/2023-30');
    expect(r).toMatchObject({ status: 'conflict', codes: ['ПРИМ13', 'ПРИМ22'] });
  });

  it('«Адмирала Макарова, ЖК WAVE, СУ-ИНЖ/» — спорный ИНДЖ/ВЕЙ2', () => {
    const r = detect('Адмирала Макарова ул., ЖК WAVE, ДГ №СУ-ИНЖ/24-79 от 25.12.24', 'СУ-ИНЖ/24-79');
    expect(r).toMatchObject({ status: 'conflict', codes: ['ВЕЙ2', 'ИНДЖ'] });
  });

  it('ЛОТ 33 — ЗИЛ33 точно', () => {
    const r = detect(
      'Автозаводская ул., вл.23/2 ЖК ЗИЛАРТ (ЛОТ 33), ДГ №СУ-ЗИЛ33/25-33 от 26.08.25',
      'СУ-ЗИЛ33/25-33',
    );
    expect(r).toMatchObject({ status: 'exact', codes: ['ЗИЛ33'] });
  });

  it('распред. письмо «Лот33 №…» и «…/Марк» — ЗИЛ33', () => {
    expect(detect('Распред.письмо № Лот33 №13/10/26 от 13.10.2026 г', 'Лот33 №13/10/26').codes).toEqual(['ЗИЛ33']);
    expect(detect('Распред.письмо № 5/10/Марк от 10.10.2026 г', '5/10/Марк').codes).toEqual(['ЗИЛ33']);
  });

  it('ЗИЛАРТ без лота — группа ЗИЛ18+ЗИЛ33', () => {
    const r = detect('Автозаводская ул., вл.23/2 ЖК ЗИЛАРТ, ДГ №СУ-ЗИЛ/25-40 от 26.08.25', 'СУ-ЗИЛ/25-40');
    expect(r).toMatchObject({ status: 'group', codes: ['ЗИЛ18', 'ЗИЛ33'] });
  });

  it('СОБЫТИЕ 6.2 — СОБ62; СОБЫТИЕ 6 — группа 6.1+6.2; СОБЫТИЕ-2 — СОБ2', () => {
    expect(detect('Раменки р-н, СОБЫТИЕ 6.2, Оплата по счету (08.06.26)')).toMatchObject({
      status: 'exact',
      codes: ['СОБ62'],
    });
    expect(detect('Раменки р-н, СОБЫТИЕ 6, Оплата по счету (08.06.26)')).toMatchObject({
      status: 'group',
      codes: ['СОБ61', 'СОБ62'],
    });
    expect(detect('Раменки р-н, СОБЫТИЕ-2, ДГ №СУ-СОБ2/2023-1 от 17.02.23', 'СУ-СОБ2/2023-1')).toMatchObject({
      status: 'exact',
      codes: ['СОБ2'],
    });
  });

  it('«МАРКЕТ» не даёт ЗИЛ33', () => {
    expect(detect('Договор поставки НОВОСТАЛЬ-МАРКЕТ №12 от 01.02.25').status).toBe('none');
  });

  it('71/13 и 71/14 — разные объекты', () => {
    expect(detect('Волоколамское ш., вл.71/13 к.13, ДГ №СУ-ПРИМ13/25-13 от 26.08.25').codes).toEqual(['ПРИМ13']);
    expect(detect('Волоколамское ш., вл.71/14 к.14, ДГ №СУ-ПРИМ14/25-51 от 26.08.25').codes).toEqual(['ПРИМ14']);
  });

  it('PRIMAVERA с адресом корпуса — точно, а не группа', () => {
    expect(detect('Волоколамское ш., вл. 71/13, ЖК PRIMAVERA, Счет №1 от 01.01.25')).toMatchObject({
      status: 'exact',
      codes: ['ПРИМ13'],
    });
  });

  it('реновация на Фридриха Энгельса — не ДОМ 56', () => {
    expect(detect('РЕНОВАЦИЯ Фридриха Энгельса ул., ДГ №СУ-ДМР/25-70 от 26.08.25', 'СУ-ДМР/25-70').status).toBe(
      'none',
    );
    expect(detect('Фридриха Энгельса ул., ДГ №СУ-ДМ/25-50 от 06.08.25', 'СУ-ДМ/25-50').codes).toEqual(['Д56']);
  });

  it('вложенные группы уточняют друг друга: Метрополия, 2-я очередь', () => {
    expect(detect('Волгоградский пр-т, вл.32/5 оч.2 этап 1.2, ДГ №СУ-МЕТ2-1.2/25-10 от 20.11.25')).toMatchObject({
      status: 'exact',
      codes: ['МЕ1.2'],
    });
    expect(detect('Волгоградский пр-т, вл.32/5 оч.2, ДГ №СУ-МЕТ2/25-3 от 20.11.25')).toMatchObject({
      status: 'group',
      codes: ['МЕ1.1', 'МЕ1.2', 'МЕ2.0'],
    });
  });

  it('поле «ОбъектВыполнения» противоречит наименованию — спорный', () => {
    const r = detect(
      'ЭЛЕКТРОЛИТНЫЙ ПР., ВЛ.7А, ДГ №28/03/23 ПТ-3 от 28.03.23',
      '28/03/23 ПТ-3',
      'Волоколамское ш., вл. 97, ЖК CITY BAY, к. 1 - 8',
    );
    expect(r.status).toBe('conflict');
    expect(r.codes).toEqual(expect.arrayContaining(['СБ1', 'ТОПХ']));
  });
});
