/**
 * Тесты на сохранение НДС строки при правке карточки.
 *
 * До этого кода PATCH карточки стирал `vat_rate`/`vat_sum` у всех позиций:
 * строки заменяются целиком, а поля НДС в новую запись не попадали. Дефект
 * тихий — суммы остаются на месте, пропадает только разбивка, и обнаруживается
 * это позже, когда карточка не может ни показать цену с налогом, ни проверить
 * арифметику по ставке.
 */
import { describe, it, expect } from 'vitest';
import { vatFieldsOf } from '../src/domain/edo/vat-fields.js';

describe('vatFieldsOf — НДС строки при сохранении карточки', () => {
  it('выделяет налог из суммы с налогом: боевой УПД № 203368', () => {
    // Вода питьевая: стоимость с налогом 4 392 ₽, ставка 22 %.
    // База 4392 / 1,22 = 3600, налог 792.
    expect(vatFieldsOf(22, '4392.00')).toEqual({ vatRate: '22', vatSum: '792' });
  });

  it('пересчитывает налог от НОВОЙ суммы, а не переносит прежний', () => {
    // Ради этого карточку и открывают: менеджер исправил сумму, и старый налог
    // к ней уже не относится. 5 000 / 1,22 = 4098,36 → налог 901,64.
    expect(vatFieldsOf('22', 5000)).toEqual({ vatRate: '22', vatSum: '901.64' });
  });

  it('ставка не пришла — поля пустые, как было до правки', () => {
    // Старые клиенты не присылают vatRate вовсе; их поведение не меняется.
    expect(vatFieldsOf(null, '4392.00')).toEqual({ vatRate: null, vatSum: null });
    expect(vatFieldsOf(undefined, '4392.00')).toEqual({ vatRate: null, vatSum: null });
    expect(vatFieldsOf('', '4392.00')).toEqual({ vatRate: null, vatSum: null });
  });

  it('нулевая ставка — это «Без НДС», а не отсутствие ставки', () => {
    // Ставку сохраняем: по ней карточка поймёт, что цена и есть цена с налогом.
    expect(vatFieldsOf(0, '1000')).toEqual({ vatRate: '0', vatSum: '0' });
  });

  it('суммы нет — ставку всё равно сохраняем', () => {
    // По ней считается цена с налогом в карточке. А налог выделять не из чего.
    expect(vatFieldsOf(22, null)).toEqual({ vatRate: '22', vatSum: null });
    expect(vatFieldsOf(22, '')).toEqual({ vatRate: '22', vatSum: null });
  });

  it('мусор вместо чисел не роняет сохранение', () => {
    expect(vatFieldsOf('не число', '4392')).toEqual({ vatRate: null, vatSum: null });
    expect(vatFieldsOf(22, 'не число')).toEqual({ vatRate: '22', vatSum: null });
  });

  it('ставка 20 % считается так же верно, как 22 %', () => {
    // Боевой УПД № 582: ставка 20, стоимость строки 848 677,50.
    // 848677,50 / 1,2 = 707 231,25 → налог 141 446,25.
    expect(vatFieldsOf(20, '848677.50')).toEqual({ vatRate: '20', vatSum: '141446.25' });
  });
});
