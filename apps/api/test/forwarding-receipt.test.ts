describe('экспедиторская расписка: разбор по тексту', () => {
  it('боевая раскладка: номер, дата, стороны, груз', () => {
    const doc = parseForwardingReceiptPages([FRONT, BACK]);
    expect(doc).toEqual({
      form: 'forwarding_receipt',
      // Номер расписки, а не ЭЭР из угла шапки и не договор экспедитора «№GL-…».
      docNumber: '26-02261022358',
      docDate: '2026-11-05',
      shipper: { name: 'ЗАО "ПО "ПРИБОР"', inn: '2200000001' },
      consignee: { name: 'ООО "СТРОЙМОНТАЖ"', inn: '7700000002' },
      items: [{ nameRaw: 'Сборный груз (534 кг, 2,18 м³)', qty: 6, unit: 'мест' }],
      confidence: 1,
    });
  });

  it('ИНН стороны не берётся из блока соседней', () => {
    // У отправителя ИНН не напечатан — ближайший следующий ИНН принадлежит
    // получателю, и подхватить его значило бы назначить поставщиком подрядчика.
    const front = FRONT.replaceAll('ИНН/КПП: 2200000001/-', '');
    const doc = parseForwardingReceiptPages([front]);
    expect(doc?.shipper).toEqual({ name: 'ЗАО "ПО "ПРИБОР"', inn: null });
    expect(doc?.consignee?.inn).toBe('7700000002');
    expect(doc?.items).toHaveLength(1);
  });

  it('неоднозначный вес не дописывается в название, места читаются', () => {
    const front = FRONT.replaceAll('всего 6 534 2,18', 'всего 6 1 534 2,18');
    const doc = parseForwardingReceiptPages([front]);
    expect(doc?.items).toEqual([{ nameRaw: 'Сборный груз', qty: 6, unit: 'мест' }]);
  });

  it('название в ёлочках и без строки наименования', () => {
    const front = FRONT.replaceAll('ЗАО "ПО "ПРИБОР"', 'ЗАО «ПО «ПРИБОР»»').replace(
      /Наименование груза[^\n]*\n[^\n]*\n/,
      '',
    );
    const doc = parseForwardingReceiptPages([front]);
    expect(doc?.shipper?.name).toBe('ЗАО «ПО «ПРИБОР»»');
    expect(doc?.items[0]?.nameRaw).toBe('Груз по экспедиторской расписке (534 кг, 2,18 м³)');
  });

  it('без номера документ не заводится', () => {
    const front = FRONT.replaceAll('№26-02261022358', '');
    expect(parseForwardingReceiptPages([front])).toBeNull();
  });

  it('без ИНН отправителя и без числа мест документ не заводится', () => {
    const front = FRONT.replaceAll('ИНН/КПП: 2200000001/-', '').replaceAll(
      'всего 6 534 2,18',
      'всего - - -',
    );
    expect(parseForwardingReceiptPages([front])).toBeNull();
  });

  it('упоминание расписки не в шапке — не расписка', () => {
    const contract = `${'Договор поставки материалов. '.repeat(15)}\nПередача груза подтверждается экспедиторской распиской №26-1 от 05.11.2026 г.`;
    expect(isForwardingReceiptLeadPage(contract)).toBe(false);
    expect(parseForwardingReceiptPages([contract])).toBeNull();
  });

  it('расписка второй страницей — не расписка', () => {
    expect(parseForwardingReceiptPages(['Спецификация к договору поставки № 15', FRONT])).toBeNull();
  });
});

describe('экспедиторская расписка: чтение PDF', () => {
  const pdf = makeTextPdfPages([
    [
      'Экспедиторская расписка',
      '№26-1 от 05.11.2026 г.',
      'Отправитель ООО "ПРИБОР"',
      'ИНН/КПП: 2200000001/-',
      'Получатель ООО "СТРОЙКА"',
      'ИНН/КПП: 7700000002/-',
      'всего 6 534 2,18',
    ],
  ]);

  it('текстовый слой PDF разбирается так же', async () => {
    const doc = await detectAndParseForwardingReceipt(pdf, 'application/pdf');
    expect(doc).toMatchObject({
      form: 'forwarding_receipt',
      docNumber: '26-1',
      docDate: '2026-11-05',
      shipper: { inn: '2200000001' },
      consignee: { inn: '7700000002' },
      items: [{ qty: 6, unit: 'мест' }],
    });
  });

  it('не PDF и битый PDF — null, маршрут не меняется', async () => {
    expect(await detectAndParseForwardingReceipt(pdf, 'image/jpeg')).toBeNull();
    expect(
      await detectAndParseForwardingReceipt(Buffer.from('%PDF-1.4\n%%EOF\n'), 'application/pdf'),
    ).toBeNull();
  });

  it('пакет: только если расписка — каждый файл', async () => {
    const other = makeTextPdfPages([['Транспортная накладная № 15 от 05.11.2026']]);
    const one = { buffer: pdf, mimeType: 'application/pdf' };
    expect((await parseForwardingReceiptBatch([one]))?.parsed.documents).toHaveLength(1);
    expect(
      await parseForwardingReceiptBatch([one, { buffer: other, mimeType: 'application/pdf' }]),
    ).toBeNull();
    expect(await parseForwardingReceiptBatch([])).toBeNull();
  });
});
