/**
 * Детектор формы 1-Т: узкий признак, потому что цена ошибки несимметрична.
 *
 * Ложное срабатывание уводит к чужому промпту накладную, которая сегодня
 * разбирается верно; пропуск оставляет всё как было. Поэтому заголовка мало —
 * нужен опознавательный знак бланка.
 */
import { describe, expect, it } from 'vitest';
import { isWaybill1tText } from '../src/domain/edo/waybill-1t-detect.js';

describe('признаки товарно-транспортной накладной формы 1-Т', () => {
  it('код формы по ОКУД опознаёт бланк', () => {
    expect(
      isWaybill1tText('ТОВАРНО-ТРАНСПОРТНАЯ НАКЛАДНАЯ\nФорма по ОКУД 0345009\nДата составления'),
    ).toBe(true);
  });

  it('номер типовой формы тоже подходит', () => {
    expect(
      isWaybill1tText('Товарно-транспортная накладная\nТиповая межотраслевая форма № 1-Т'),
    ).toBe(true);
  });

  it('товарный раздел бланка — самостоятельный признак', () => {
    expect(
      isWaybill1tText(
        'ТОВАРНО-ТРАНСПОРТНАЯ НАКЛАДНАЯ № 16 743\nI. ТОВАРНЫЙ РАЗДЕЛ (заполняется грузоотправителем)',
      ),
    ).toBe(true);
  });

  it('транспортная накладная формы 2116 остаётся чужой', () => {
    // Её разбирает активный промпт накладных, и трогать этот путь нельзя.
    expect(
      isWaybill1tText(
        'ТРАНСПОРТНАЯ НАКЛАДНАЯ № 199\nПостановление Правительства РФ от 21.12.2020 № 2116',
      ),
    ).toBe(false);
  });

  it('одного заголовка без признаков формы недостаточно', () => {
    expect(isWaybill1tText('Товарно-транспортная накладная прилагается к письму')).toBe(false);
  });

  it('УПД и пустой текст — не 1-Т', () => {
    expect(isWaybill1tText('Универсальный передаточный документ. Счёт-фактура № 42')).toBe(false);
    expect(isWaybill1tText('')).toBe(false);
  });
});
