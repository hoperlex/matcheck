import { z } from 'zod';

/**
 * Групповой протокол операций: приёмка и отгрузка машины целиком.
 *
 * Живёт отдельным модулем, потому что нужен ОБЕИМ операциям в одинаковом виде.
 * Разъедься поля между deliveries и shipments — и мобильный клиент придётся
 * учить двум диалектам одного и того же, а сервер получит две реализации
 * проверки состава, которые разойдутся при первой правке.
 *
 * Почему три поля, а не одно. Без capability сервер не может отличить старую
 * сборку от новой: обе не присылают groupId. Без groupId он не знает, что
 * клиент вообще имел в виду машину. Без groupRevision «состав тот же, но суммы
 * другие» не ловится сравнением множества id — инспектор подтвердил бы позиции,
 * которых не видел.
 */

/**
 * Что умеет клиент, список через запятую — тот же формат, что у query-параметра
 * `capabilities` в GET /sync.
 *
 * Отсутствие поля означает старую сборку, и это ЗАКОННОЕ состояние: сервер
 * обязан провести такую операцию по прежнему пути. Именно поэтому проверки
 * группы не могут опираться на один лишь groupId — его не присылают обе
 * стороны, и старая, и просто одиночная приёмка.
 */
export const CapabilitiesField = z.string().optional();

/**
 * Машина, к которой относится операция, — id корневого пакета загрузки.
 *
 * ОСС-токен, а не источник истины: сервер вычисляет группу сам и лишь сверяет
 * с присланным. Клиент не может ни расширить состав, ни назначить документам
 * чужую машину — расхождение означает, что планшет работает с устаревшим
 * представлением, и операция отклоняется typed-конфликтом.
 */
export const GroupIdField = z.string().uuid().optional();

/**
 * Версия состава машины на момент, когда планшет открыл форму.
 *
 * Растёт и при изменении состава, и при изменении реквизитов или позиций любого
 * документа группы. Сверяется перед записью операции: инспектор не должен
 * подтверждать материалы, которых он не видел.
 */
export const GroupRevisionField = z.number().int().nonnegative().optional();

/** Поля группового протокола для спреда в схемы upsert обеих операций. */
export const GroupOperationFields = {
  capabilities: CapabilitiesField,
  groupId: GroupIdField,
  groupRevision: GroupRevisionField,
} as const;

/**
 * Typed-отказы группового протокола.
 *
 * Каждый код существует потому, что клиент обязан отреагировать на него
 * ПО-РАЗНОМУ, и «просто ошибка» тут недопустима: неизвестный 4xx мобильный
 * классификатор превращает в Drop, то есть в молча потерянную работу
 * инспектора.
 *
 *   * `group_claimed` — машину уже оформляет другой планшет. Локальный дубль
 *     уходит в карантин, инспектору показывают, кем и когда занята машина.
 *   * `group_changed` — состав или содержимое машины изменились. Черновик
 *     сохраняется, документы обновляются, форма просит повторную проверку.
 *   * `source_documents_not_ready` — какой-то документ машины ещё не обработан.
 *     Черновик сохраняется и ждёт готовности; это не ошибка инспектора.
 *   * `group_incomplete` — прислано подмножество или посторонний документ.
 *     Списки missing/extra нужны, чтобы объяснить, что именно разошлось.
 */
export const GroupConflictCodes = [
  'group_claimed',
  'group_changed',
  'source_documents_not_ready',
  'group_incomplete',
] as const;
export type GroupConflictCode = (typeof GroupConflictCodes)[number];

export const GroupConflictSchema = z.object({
  error: z.enum(GroupConflictCodes),
  /** Машина, о которой идёт речь. */
  groupId: z.string().uuid().nullable(),
  /** Актуальная версия состава — клиент обновляет форму по ней. */
  groupRevision: z.number().int().nullable().optional(),
  /** Полный канонический состав: что именно сервер ожидал получить. */
  expectedDocumentIds: z.array(z.string().uuid()).optional(),
  /** Чего не хватило в присланном наборе. */
  missingDocumentIds: z.array(z.string().uuid()).optional(),
  /** Что прислано лишнего. */
  extraDocumentIds: z.array(z.string().uuid()).optional(),
  /** Кем занята машина — только для group_claimed. */
  claimedByOperationId: z.string().uuid().nullable().optional(),
  claimedAt: z.string().nullable().optional(),
});
export type GroupConflict = z.infer<typeof GroupConflictSchema>;
